#!/usr/bin/env bash
# The Direct3D 12 backend's own shaders (shaders/dx12.hlsl), DXIL only, into
# src/dx12/shaders.rs: the pinned dxc (shaders/fetch-dxc.sh), signed, without debug
# information or reflection, as render3d/hlsl-rs.sh compiles the plugins'. A pixel
# shader's entry `ps_<name>` is compiled with `<NAME>` defined (the source keeps each
# one's texture at t0 apart). Committed, so a machine without dxc builds; run it after
# changing dx12.hlsl.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
src="$here/shaders/dx12.hlsl"
out="$here/src/dx12/shaders.rs"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
dxc=${DXC:-}
[ -n "$dxc" ] || dxc=$("$here/shaders/fetch-dxc.sh") ||
    { echo "dx12-shaders.sh: the pinned dxc could not be fetched (shaders/fetch-dxc.sh)" >&2; exit 1; }

{
    echo "// generated by gpu/dx12-shaders.sh from shaders/dx12.hlsl -- do not edit"
    for e in $(sed -n 's#^// entries:##p' "$src"); do
        IFS=: read -r entry stage sym <<< "$e"
        defs=()
        [ "$stage" = ps ] && defs=(-D "$(echo "${entry#ps_}" | tr a-z A-Z)")
        "$dxc" -Qstrip_debug -Qstrip_reflect "${defs[@]}" -T "${stage}_6_0" -E "$entry" -Fo "$tmp/$sym.dxil" "$src" > "$tmp/err" 2>&1 ||
            { cat "$tmp/err" >&2; echo "dx12-shaders.sh: $entry failed" >&2; exit 1; }
        python3 - "$tmp/$sym.dxil" <<'PY' || { echo "dx12-shaders.sh: $entry: the DXIL is not signed" >&2; exit 1; }
import sys
b = open(sys.argv[1], 'rb').read()
sys.exit(0 if b[:4] == b'DXBC' and any(b[4:20]) and len(b) % 4 == 0 else 1)
PY
        n=$(( $(stat -c %s "$tmp/$sym.dxil") / 4 ))
        echo "pub static $sym: [u32; $n] = [ // $entry, ${stage}_6_0"
        od -An -v -tx4 -w16 "$tmp/$sym.dxil" | sed 's/ \([0-9a-f]\{8\}\)/ 0x\1,/g; s/^ /   /'
        echo "];"
    done
} > "$tmp/shaders.rs"
mkdir -p "$(dirname "$out")"
mv "$tmp/shaders.rs" "$out"
echo "dx12-shaders.sh: wrote $out"
