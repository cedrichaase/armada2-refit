#!/usr/bin/env bash
# The Vulkan backend's own shaders (shaders/vk_*.hlsl), SPIR-V only, into
# src/vulkan/shaders.rs: dxc, Vulkan 1.1, as render3d/hlsl-rs.sh compiles the plugins'
# (vertex shaders with -fvk-invert-y), each put through spirv-val. Committed, so a
# machine without dxc builds; run it after changing a vk_*.hlsl.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
out="$here/src/vulkan/shaders.rs"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
command -v dxc >/dev/null && command -v spirv-val >/dev/null ||
    { echo "vk-shaders.sh: dxc or spirv-val is not installed (Arch: directx-shader-compiler, spirv-tools)" >&2; exit 1; }

{
    echo "// generated by gpu/vk-shaders.sh from shaders/vk_*.hlsl -- do not edit"
    for src in "$here"/shaders/vk_*.hlsl; do
        for e in $(sed -n 's#^// entries:##p' "$src"); do
            IFS=: read -r entry stage sym <<< "$e"
            flags=(-spirv -fspv-target-env=vulkan1.1 -fvk-use-dx-layout)
            [ "$stage" = vs ] && flags+=(-fvk-invert-y)
            dxc "${flags[@]}" -T "${stage}_6_0" -E "$entry" -Fo "$tmp/$sym.spv" "$src" > "$tmp/err" 2>&1 ||
                { cat "$tmp/err" >&2; echo "vk-shaders.sh: $src:$entry failed" >&2; exit 1; }
            spirv-val --target-env vulkan1.1 "$tmp/$sym.spv"
            n=$(( $(stat -c %s "$tmp/$sym.spv") / 4 ))
            echo "pub static $sym: [u32; $n] = [ // $entry, $(basename "$src")"
            od -An -v -tx4 -w16 "$tmp/$sym.spv" | sed 's/ \([0-9a-f]\{8\}\)/ 0x\1,/g; s/^ /   /'
            echo "];"
        done
    done
} > "$tmp/shaders.rs"
mv "$tmp/shaders.rs" "$out"
echo "vk-shaders.sh: wrote $out"
