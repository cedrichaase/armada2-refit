//! The settings descriptors, contract A2SET_ABI 1.0 (tools/settings/README.md): the row
//! of a `<Plugin>_Settings` table and the readers a plugin reads its keys through. The
//! layout between the markers is written by `tools/settings/gen.py` from its schema, as
//! is the `A2Setting` of `csdk/a2asi.h`; each plugin's table is generated from its
//! `settings.toml` into `settings_table.rs` (or `.h`).
//!
//! A plugin reads a row's key only through its row, `on(&ini, ROW)` / `int` / `float`
//! / `value`, so the code's default is the table's by construction. The value comes
//! from the overlay first (`RefitPlayer.ini`, `Ini::lookup`), then the plugin's ini,
//! then the row's `def`.
use crate::Ini;
use alloc::string::String;
use core::ffi::c_char;

