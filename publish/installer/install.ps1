<#
Armada II Refit -- install the release package into the game, on Windows.

  install.bat [<game dir>]                 install
  install.bat -Uninstall [<game dir>]      take all of it out again

No choices to make: what can work here is installed, the rest is skipped and says why.
First the prerequisites (prereqs.txt: the ASI loader with STA2WidescreenPatch), bundled in
vendor\, each file only if it is missing. Then the Direct3D chain: crosire's d3d8to9 as
d3d8.dll (chain\), in place of GOG's own d3d8to9 build, on Windows' own Direct3D 9. In
front of it Display8 (display\), the game's d3d8.dll of ours, with d3d8to9 behind it as
d3d8_real.dll: in stub mode, as shipped, the engine draws nothing and Render3D.asi (the 3D
view) and UI.asi (the HUD, the menus and the loading screen) draw the whole frame on
Display8's own device, the first that starts of Vulkan, Direct3D 12 and Direct3D 9. Where
the chain is left as it is, Display8 stays out, the UI's place is taken by the plugins it
supersedes (HUD.asi, Menus.asi, GridLayout.asi) and the 3D view stays the engine's.
The models are rewritten from the player's own SOD files with Python 3 (py, python or
A2_PYTHON), skipped without it.

The game directory is the one holding Armada2.exe: the argument, else this folder's
parent if the package was unzipped into the game, else the GOG install found in the
registry, else it asks. PowerShell 5.1 or later; install.bat runs it.

For the GUI installer, as install.sh: A2_PROGRESS=1 prints "::step <id> <what>" as each
stage starts (the ids are manifest.json's "steps"), A2_SKIP="cutscenes" leaves the
cutscene player out, and A2_PYTHON names the program that runs the model scripts. Every
line goes to stdout through [Console]::Out, in order; an error is the last line, on
stderr, and the exit code is 1. With A2_PROGRESS=1 an error the GUI can explain is first
named on stdout as "::error <code> <path>", one line per file (codes: av-locked,
av-missing, damaged, game-running, no-game, write-denied; gui-installer/README.md,
"Errors").
#>
param(
    [string]$GameDir = "",
    [switch]$Uninstall
)
$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"   # Invoke-WebRequest's bar: slow, and not output

# One way out for every line, so a reader of the pipe sees them in the order written:
# Write-Host and Write-Warning go through the host, which may buffer apart from it.
function Say([string]$s) { [Console]::Out.WriteLine($s) }
# Any error ends the install: its message plainly, as the last line, and exit code 1.
trap {
    [Console]::Out.Flush()
    [Console]::Error.WriteLine($_.Exception.Message)
    exit 1
}

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$DxvkMarker = "# generated by tools/renderer-config.sh"   # dxvk.conf files we wrote

function Step([string]$id, [string]$what) { if ($env:A2_PROGRESS -eq "1") { Say "::step $id $what" } }
# An error the GUI installer can explain: "::error <code> <path>" for each file, then the
# sentence for a person, as the last line.
function Stop-With([string]$code, [string[]]$paths, [string]$msg) {
    if ($env:A2_PROGRESS -eq "1") { foreach ($p in $paths) { Say "::error $code $p" } }
    throw $msg
}
# Some antivirus programs flag the plugins (unsigned DLLs that hook a game) as a false
# positive, quarantine them or hold them open; this says so, and what to do.
$AvHelp = "https://github.com/cedrichaase/armada2-refit#antivirus-false-positives"
function Av-Advice { "Some antivirus programs flag Armada II Refit's plugins as a false positive. " +
    "Restore the files from the antivirus's quarantine, or add exclusions for $here and $GameDir, " +
    "then try again ($AvHelp)." }
# A2_SKIP="cutscenes ..." leaves those parts out. Only cutscenes can be skipped so far.
function Test-Skipped([string]$n) { (" " + $env:A2_SKIP + " ") -like "* $n *" }

function Test-Game([string]$d) { $d -and (Test-Path -LiteralPath (Join-Path $d "Armada2.exe")) }

if (-not (Test-Game $GameDir)) {
    if ($GameDir) { Stop-With no-game @($GameDir) "no Armada2.exe in $GameDir" }
    $parent = Split-Path -Parent $here
    if (Test-Game $parent) { $GameDir = $parent }
}
if (-not $GameDir) {
    foreach ($k in @("HKLM:\SOFTWARE\WOW6432Node\GOG.com\Games", "HKLM:\SOFTWARE\GOG.com\Games")) {
        if (-not (Test-Path $k)) { continue }
        foreach ($g in Get-ChildItem $k) {
            $p = Get-ItemProperty $g.PSPath
            if ($p.gameName -like "*Armada II*" -and (Test-Game $p.path)) { $GameDir = $p.path; break }
        }
        if ($GameDir) { break }
    }
}
if (-not $GameDir) { $GameDir = (Read-Host "Game directory (the folder with Armada2.exe)").Trim('"') }
if (-not (Test-Game $GameDir)) { Stop-With no-game @($GameDir) "no Armada2.exe in $GameDir -- pass the game directory as an argument" }
$GameDir = (Resolve-Path -LiteralPath $GameDir).Path

if (Get-Process -Name armada2 -ErrorAction SilentlyContinue) { Stop-With game-running @("Armada2.exe") "Armada2.exe is running -- quit the game first" }

function G([string]$n) { Join-Path $GameDir $n }
$Manifest = G "armada2-refit-prereqs.txt"   # what the prerequisites and chain steps added
function Get-Sha([string]$f) { (Get-FileHash -Algorithm SHA256 -LiteralPath $f).Hash.ToLower() }
# DXVK by content, never by name: GOG puts a d3d8.dll there too.
function Test-Dxvk([string]$f) {
    (Test-Path -LiteralPath $f) -and
        ([Text.Encoding]::ASCII.GetString([IO.File]::ReadAllBytes($f)) -match "(?i)dxvk")
}
# crosire's d3d8to9 1.16.0, as the repository's ./install places it (platform/vendor/), by hash.
function Test-D3d8to9([string]$f) {
    (Test-Path -LiteralPath $f) -and ((Get-Sha $f) -eq "122928cfe225c25d30decf7184a5d37e490cecf3b58256ba3206c7e1853f8ab8")
}
# GOG's own d3d8.dll (its d3d8to9 build), as the release ships it. Kept as
# d3d8.dll.gog-backup, the name platform/d3d8-chain.py gives it, when replaced.
function Test-GogD3d8([string]$f) {
    (Test-Path -LiteralPath $f) -and ((Get-Sha $f) -eq "735dbb81a5fa0368c6436349fc5bf97a9ae15daeb6829dfe95a17704294e6719")
}
$ChainBackup = ".a2chain-backup"   # any other d3d8.dll the chain step replaced
# Display8 (display\), by content: the panic message every build carries (its hash
# changes with every build). Display8 holds the word "dxvk" too, so ask this first.
function Test-Display8([string]$f) {
    (Test-Path -LiteralPath $f) -and
        [Text.Encoding]::ASCII.GetString([IO.File]::ReadAllBytes($f)).Contains("Display8 stopped the game")
}
# What Display8 writes beside the exe (display/install --remove takes the same out).
$DisplayFiles = "Display8.ini", "Display8.log", "Display8.inventory.tsv", "Display8.inventory.tmp", "Display8.mark", "Display8.go"
# Display8 out of the d3d8 slot, and the chain's d3d8.dll it stood in front of
# (d3d8_real.dll) back in it. With -All, its settings, logs and pipeline cache go too.
function Remove-Display8([switch]$All) {
    if (Test-Display8 (G "d3d8.dll")) {
        Remove-Item -LiteralPath (G "d3d8.dll")
        if (Test-Path -LiteralPath (G "d3d8_real.dll")) { Move-Item -LiteralPath (G "d3d8_real.dll") (G "d3d8.dll") }
    }
    if ($All) {
        foreach ($n in $DisplayFiles) { Remove-Item -LiteralPath (G $n) -ErrorAction SilentlyContinue }
        # The repository's display/install leaves these: a2mod's copy of the chain, and
        # d3d8to9 behind a Display8 since taken out by hand.
        Remove-Item -LiteralPath (G "d3d8.dll.a2display-backup") -ErrorAction SilentlyContinue
        if (Test-D3d8to9 (G "d3d8_real.dll")) { Remove-Item -LiteralPath (G "d3d8_real.dll") }
        # Its Vulkan pipeline cache (display/src/vk/cache.rs); the folder is the GUI
        # installer's too, so only the file.
        if ($env:LOCALAPPDATA) {
            Remove-Item -LiteralPath (Join-Path $env:LOCALAPPDATA "armada2-refit\Display8.pipelines") -ErrorAction SilentlyContinue
        }
    }
}
function Test-Proxy([string]$f) {
    (Test-Path -LiteralPath $f) -and (Select-String -LiteralPath $f -Pattern "BinkProxy" -SimpleMatch -Quiet)
}
function Test-OurDxvkConf {
    (Test-Path -LiteralPath (G "dxvk.conf")) -and
        (Select-String -LiteralPath (G "dxvk.conf") -Pattern $DxvkMarker -SimpleMatch -Quiet)
}
# The proxy out again, the stock binkw32.dll back.
function Remove-Proxy {
    if (Test-Proxy (G "binkw32.dll")) {
        if (Test-Path -LiteralPath (G "binkw32.dll.a2neb-backup")) {
            Move-Item -LiteralPath (G "binkw32.dll.a2neb-backup") (G "binkw32.dll") -Force
            Remove-Item -LiteralPath (G "binkw32_orig.dll") -ErrorAction SilentlyContinue
        } elseif (Test-Path -LiteralPath (G "binkw32_orig.dll")) {
            Move-Item -LiteralPath (G "binkw32_orig.dll") (G "binkw32.dll") -Force
        } else {
            Say "WARNING: binkw32.dll is the proxy and there is no stock copy -- restore it by hand"
        }
    }
    foreach ($n in "BinkProxy.ini", "BinkProxy.log") { Remove-Item -LiteralPath (G $n) -ErrorAction SilentlyContinue }
}

# Python 3 for the SOD rewrites (models\): A2_PYTHON (the GUI installer's own, run as
# "<exe> script.py args"), else the py launcher, else a python on PATH -- each but
# A2_PYTHON only if it runs as Python 3, which keeps out the Microsoft Store's python.exe
# alias (WindowsApps), a stub that offers to install Python. Returns the command and its
# leading arguments, or nothing.
function Test-Python3([string]$exe, [string[]]$pre) {
    $psi = New-Object Diagnostics.ProcessStartInfo
    $psi.FileName = $exe
    $psi.Arguments = (@($pre) + @('-c', '"import sys; sys.exit(sys.version_info[0] != 3)"')) -join " "
    $psi.UseShellExecute = $false; $psi.CreateNoWindow = $true
    $psi.RedirectStandardOutput = $true; $psi.RedirectStandardError = $true
    try {
        $p = [Diagnostics.Process]::Start($psi)
        if (-not $p.WaitForExit(15000)) { try { $p.Kill() } catch { }; return $false }
        return ($p.ExitCode -eq 0)
    } catch { return $false }
}
function Find-Python {
    if ($env:A2_PYTHON) { return $env:A2_PYTHON }
    $py = Get-Command py -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($py -and (Test-Python3 $py.Source @("-3"))) { return @($py.Source, "-3") }
    foreach ($c in @(Get-Command python -CommandType Application -ErrorAction SilentlyContinue)) {
        if (Test-Python3 $c.Source @()) { return $c.Source }
    }
}
# The SOD rewrites, with the game they work on. A failure is said and the rest goes on.
function Invoke-Sods([string]$mode) {   # --install | --revert
    $ErrorActionPreference = "Continue"   # a script's stderr is output here, not an error
    $env:A2_GAME = $GameDir
    $exe = $Py[0]; $pre = @($Py | Select-Object -Skip 1)
    foreach ($s in "moon-sod", "select-sod", "hull-sod", "asteroid-sod") {
        $file = Join-Path $here "models\$s.py"
        try {
            & $exe @pre $file $mode 2>&1 | ForEach-Object { Say "    $_" }
            $code = $LASTEXITCODE
        } catch {
            Say "    $($_.Exception.Message)"; $code = 1
        }
        if ($code -ne 0) { Say "  $s.py $mode failed -- the rest goes on" }
    }
}

# The per-part plugins earlier packages put in, replaced by Render3D.asi: taken out, in
# every case (a module of Render3D.asi stands down beside its old plugin).
function Remove-OldPlugins {
    foreach ($n in "MSAA", "Planets", "Lighting", "Sky", "Nebulae", "Surfaces", "Explosions", "Shields", "Repair", "Venting", "Specials", "Fog") {
        foreach ($e in ".asi", ".ini", ".log") { Remove-Item -LiteralPath (G "$n$e") -ErrorAction SilentlyContinue }
    }
    # Sky.asi's recipes (one per sky name, mbg*.ini); anything else there is the player's.
    if (Test-Path -LiteralPath (G "Sky")) {
        Get-ChildItem -LiteralPath (G "Sky") -Filter "mbg*.ini" | Remove-Item -ErrorAction SilentlyContinue
        if (-not (Get-ChildItem -Force -LiteralPath (G "Sky"))) { Remove-Item -LiteralPath (G "Sky") }
    }
}

# Render3D.asi's recipes: Surfaces\ and Nebulae\ in the game directory, only the files of
# these names; anything else there is the player's.
$Recipes = "Surfaces", "Nebulae"
function Remove-Recipes {
    foreach ($d in $Recipes) {
        if (-not (Test-Path -LiteralPath (G $d))) { continue }
        foreach ($f in Get-ChildItem -LiteralPath (Join-Path $here "game\$d") -Filter "*.ini") {
            Remove-Item -LiteralPath (Join-Path (G $d) $f.Name) -ErrorAction SilentlyContinue
        }
        if (-not (Get-ChildItem -Force -LiteralPath (G $d))) { Remove-Item -LiteralPath (G $d) }
    }
}
# The plugins UI.asi takes the place of (ui/supersede.sh), and Menus.asi's old name.
function Remove-LegacyUi {
    foreach ($n in "HUD", "Menus", "MenuScale", "GridLayout") {
        foreach ($e in ".asi", ".ini", ".log") { Remove-Item -LiteralPath (G "$n$e") -ErrorAction SilentlyContinue }
    }
}

# Packages before 13.0.0 put a bloom preset in for ReShade (A2Bloom.ini, and a copy as
# ReShadePreset.ini when the player had none); Render3D.asi blooms the 3D view itself
# now. The preset goes only while it is still that copy; ReShade itself is the player's.
function Remove-OldBloom {
    $ours = G "A2Bloom.ini"
    if (-not (Test-Path -LiteralPath $ours)) { return }
    $preset = G "ReShadePreset.ini"
    if ((Test-Path -LiteralPath $preset) -and (Get-Sha $preset) -eq (Get-Sha $ours)) {
        Remove-Item -LiteralPath $preset
    }
    Remove-Item -LiteralPath $ours
    Say "  removed the old bloom preset (A2Bloom.ini)"
}

