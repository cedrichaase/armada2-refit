# One way out for every line, so a reader of the pipe sees them in the order written:
# Write-Host and Write-Warning go through the host, which may buffer apart from it.
function Say([string]$s) { [Console]::Out.WriteLine($s) }
# Any error ends the install: its message plainly, as the last line, and exit code 1.
trap {
    [Console]::Out.Flush()
    [Console]::Error.WriteLine($_.Exception.Message)
    exit 1
}

