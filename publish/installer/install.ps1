# The ASI loader and STA2WidescreenPatch (prereqs.txt), in vendor\<name>\ because their
# licence allows it. A file already in the game directory is never overwritten. What this
# adds is recorded in $Manifest with its hash, so -Uninstall takes out only that, and
# only unchanged.
function Add-Record([string]$f) { Add-Content -LiteralPath $Manifest "$f $(Get-Sha (G $f))" }
# A file of the package into the game. What stops it is named: the package's copy gone or
# held (an antivirus, after the check above), else the game folder refusing the write
# (an antivirus guarding DLLs there, or a folder that needs administrator rights).
function Copy-Into([string]$src, [string]$dst) {
    try { Copy-Item -LiteralPath $src $dst -Force }
    catch {
        $why = $_.Exception.Message
        if (-not (Test-Path -LiteralPath $src)) {
            Stop-With av-missing @(Rel $src) "$(Rel $src) has gone from the package. An antivirus has most likely quarantined it. $(Av-Advice)"
        }
        if (-not (Test-Readable $src)) {
            Stop-With av-locked @(Rel $src) "$(Rel $src) from the package could not be read. An antivirus has most likely locked it. $(Av-Advice)"
        }
        Stop-With write-denied @($dst) ("$(Split-Path -Leaf $dst) could not be written into $GameDir ($why). " +
            "An antivirus may be blocking it, or the folder needs administrator rights: add an exclusion " +
            "for $GameDir, or run the installer as administrator, then try again ($AvHelp).")
    }
}

