function Get-Sha([string]$f) { (Get-FileHash -Algorithm SHA256 -LiteralPath $f).Hash.ToLower() }
# DXVK by content, never by name: GOG puts a d3d8.dll there too.
function Test-Dxvk([string]$f) {
    (Test-Path -LiteralPath $f) -and
        ([Text.Encoding]::ASCII.GetString([IO.File]::ReadAllBytes($f)) -match "(?i)dxvk")
}
# crosire's d3d8to9 1.16.0, as the repository's ./install places it (platform/vendor/), by hash.
function Test-D3d8to9([string]$f) {
    (Test-Path -LiteralPath $f) -and ((Get-Sha $f) -eq "122928cfe225c25d30decf7184a5d37e490cecf3b58256ba3206c7e1853f8ab8")
}
# GOG's own d3d8.dll (its d3d8to9 build), as the release ships it. Kept as
# d3d8.dll.gog-backup, the name platform/d3d8-chain.py gives it, when replaced.
function Test-GogD3d8([string]$f) {
    (Test-Path -LiteralPath $f) -and ((Get-Sha $f) -eq "735dbb81a5fa0368c6436349fc5bf97a9ae15daeb6829dfe95a17704294e6719")
}
$ChainBackup = ".a2chain-backup"   # any other d3d8.dll / d3d9.dll an install before 15.6.0 replaced
# Display8 (display\), by content: the panic message every build carries (its hash
# changes with every build). Display8 holds the word "dxvk" too, so ask this first.
function Test-Display8([string]$f) {
    (Test-Path -LiteralPath $f) -and
        [Text.Encoding]::ASCII.GetString([IO.File]::ReadAllBytes($f)).Contains("Display8 stopped the game")
}
# What Display8 writes beside the exe (display/install --remove takes the same out).
# Its log, like every plugin's since 13.50.0, is in %LOCALAPPDATA%\armada2-refit\logs:
# an uninstall leaves that folder (the bug report reads it); the names here are what
# older builds wrote beside the exe.
$DisplayFiles = "Display8.ini", "Display8.log", "Display8.inventory.tsv", "Display8.inventory.tmp", "Display8.mark", "Display8.go"
# Display8 out of the d3d8 slot. An older Display8 stood in front of a d3d8_real.dll: one
# that is not the vendored d3d8to9 (retire.txt takes that one out) is put back in the slot.
# With -All, its settings, logs and pipeline cache go too.
function Remove-Display8([switch]$All) {
    if (Test-Display8 (G "d3d8.dll")) {
        Remove-Item -LiteralPath (G "d3d8.dll")
        if ((Test-Path -LiteralPath (G "d3d8_real.dll")) -and -not (Test-D3d8to9 (G "d3d8_real.dll"))) {
            Move-Item -LiteralPath (G "d3d8_real.dll") (G "d3d8.dll")
        }
    }
    if ($All) {
        foreach ($n in $DisplayFiles) { Remove-Item -LiteralPath (G $n) -ErrorAction SilentlyContinue }
        # Its Vulkan pipeline cache (display/src/vk/cache.rs) and Direct3D 12 pipeline
        # library (display/src/dx12/cache.rs); the folder is the GUI installer's too,
        # and holds the logs, so only the files.
        if ($env:LOCALAPPDATA) {
            Remove-Item -LiteralPath (Join-Path $env:LOCALAPPDATA "armada2-refit\Display8.pipelines") -ErrorAction SilentlyContinue
            Remove-Item -LiteralPath (Join-Path $env:LOCALAPPDATA "armada2-refit\Display8.d3d12pipelines") -ErrorAction SilentlyContinue
        }
    }
}
function Test-Proxy([string]$f) {
    (Test-Path -LiteralPath $f) -and (Select-String -LiteralPath $f -Pattern "BinkProxy" -SimpleMatch -Quiet)
}
# The proxy out again, the stock binkw32.dll back.
function Remove-Proxy {
    if (Test-Proxy (G "binkw32.dll")) {
        if (Test-Path -LiteralPath (G "binkw32.dll.a2neb-backup")) {
            Move-Item -LiteralPath (G "binkw32.dll.a2neb-backup") (G "binkw32.dll") -Force
            Remove-Item -LiteralPath (G "binkw32_orig.dll") -ErrorAction SilentlyContinue
        } elseif (Test-Path -LiteralPath (G "binkw32_orig.dll")) {
            Move-Item -LiteralPath (G "binkw32_orig.dll") (G "binkw32.dll") -Force
        } else {
            Say "WARNING: binkw32.dll is the proxy and there is no stock copy -- restore it by hand"
        }
    }
    foreach ($n in "BinkProxy.ini", "BinkProxy.log") { Remove-Item -LiteralPath (G $n) -ErrorAction SilentlyContinue }
}

# Python 3 for the SOD rewrites (models\): A2_PYTHON (the GUI installer's own, run as
# "<exe> script.py args"), else the py launcher, else a python on PATH -- each but
# A2_PYTHON only if it runs as Python 3, which keeps out the Microsoft Store's python.exe
# alias (WindowsApps), a stub that offers to install Python. Returns the command and its
# leading arguments, or nothing.
function Test-Python3([string]$exe, [string[]]$pre) {
    $psi = New-Object Diagnostics.ProcessStartInfo
    $psi.FileName = $exe
    $psi.Arguments = (@($pre) + @('-c', '"import sys; sys.exit(sys.version_info[0] != 3)"')) -join " "
    $psi.UseShellExecute = $false; $psi.CreateNoWindow = $true
    $psi.RedirectStandardOutput = $true; $psi.RedirectStandardError = $true
    try {
        $p = [Diagnostics.Process]::Start($psi)
        if (-not $p.WaitForExit(15000)) { try { $p.Kill() } catch { }; return $false }
        return ($p.ExitCode -eq 0)
    } catch { return $false }
}
function Find-Python {
    if ($env:A2_PYTHON) { return $env:A2_PYTHON }
    $py = Get-Command py -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($py -and (Test-Python3 $py.Source @("-3"))) { return @($py.Source, "-3") }
    foreach ($c in @(Get-Command python -CommandType Application -ErrorAction SilentlyContinue)) {
        if (Test-Python3 $c.Source @()) { return $c.Source }
    }
}
# The SOD rewrites, with the game they work on. A failure is said and the rest goes on.
function Invoke-Sods([string]$mode) {   # --install | --revert
    $ErrorActionPreference = "Continue"   # a script's stderr is output here, not an error
    $env:A2_GAME = $GameDir
    $exe = $Py[0]; $pre = @($Py | Select-Object -Skip 1)
    foreach ($s in "moon-sod", "select-sod", "hull-sod", "asteroid-sod") {
        $file = Join-Path $here "models\$s.py"
        try {
            & $exe @pre $file $mode 2>&1 | ForEach-Object { Say "    $_" }
            $code = $LASTEXITCODE
        } catch {
            Say "    $($_.Exception.Message)"; $code = 1
        }
        if ($code -ne 0) { Say "  $s.py $mode failed -- the rest goes on" }
    }
}

# Render3D.asi's recipes: Surfaces\ and Nebulae\ in the game directory, only the files of
# these names; anything else there is the player's.
$Recipes = "Surfaces", "Nebulae"
function Remove-Recipes {
    foreach ($d in $Recipes) {
        if (-not (Test-Path -LiteralPath (G $d))) { continue }
        foreach ($f in Get-ChildItem -LiteralPath (Join-Path $here "layers\render3d\$d") -Filter "*.ini") {
            Remove-Item -LiteralPath (Join-Path (G $d) $f.Name) -ErrorAction SilentlyContinue
        }
        if (-not (Get-ChildItem -Force -LiteralPath (G $d))) { Remove-Item -LiteralPath (G $d) }
    }
}
# What earlier versions installed and nothing installs now: retire.txt, retire\known.txt
# without its comments, one entry a line (retire\README.md has the kinds). Each entry is
# recognised by what it is -- a plugin by name, the chain's binaries by hash, dxvk.conf by
# our marker -- so a file of the player's own stays. The old bloom is the bloom step's.
$script:Retired = $false
function Remove-Retired([string]$path) {   # a file in the game directory
    if (Test-Path -LiteralPath $path -PathType Leaf) {
        Remove-Item -LiteralPath $path -Force
        Say "  retired $($path.Substring($GameDir.Length + 1))"; $script:Retired = $true
    }
}
function Remove-Empty([string]$dir) {
    if ((Test-Path -LiteralPath $dir -PathType Container) -and -not (Get-ChildItem -Force -LiteralPath $dir)) {
        Remove-Item -LiteralPath $dir -ErrorAction SilentlyContinue
    }
}
function Remove-ManifestRecord([string]$name) {   # a file recorded for -Uninstall that is gone now
    if (Test-Path -LiteralPath $Manifest) {
        $keep = @(Get-Content -LiteralPath $Manifest | Where-Object { -not $_.StartsWith("$name ") })
        $text = ""; if ($keep.Count) { $text = ($keep -join "`n") + "`n" }
        [IO.File]::WriteAllText($Manifest, $text)
    }
}
function Invoke-Retire {
    $table = Join-Path $here "retire.txt"
    if (-not (Test-Path -LiteralPath $table)) { return }
    foreach ($line in Get-Content -LiteralPath $table) {
        $line = $line.Trim()
        if (-not $line -or $line.StartsWith("#")) { continue }
        $w = @($line -split "\s+")
        $kind = $w[0]; $rest = @($w | Select-Object -Skip 1)
        switch ($kind) {
            "plugin" {
                foreach ($n in $rest) { foreach ($e in "asi", "ini", "log") { Remove-Retired (G "$n.$e") } }
            }
            "plugin-dir" {
                foreach ($d in $rest) {
                    if (-not (Test-Path -LiteralPath (G $d) -PathType Container)) { continue }
                    foreach ($f in @(Get-ChildItem -LiteralPath (G $d) -Filter "*.bmp" -File)) { Remove-Retired $f.FullName }
                    Remove-Empty (G $d)
                }
            }
            "glob" {
                if (-not (Test-Path -LiteralPath (G $rest[0]) -PathType Container)) { continue }
                foreach ($f in @(Get-ChildItem -LiteralPath (G $rest[0]) -Filter $rest[1] -File)) { Remove-Retired $f.FullName }
                Remove-Empty (G $rest[0])
            }
            "glob-hash" {
                if (-not (Test-Path -LiteralPath (G $rest[0]) -PathType Container)) { continue }
                $known = @($rest | Select-Object -Skip 2)
                foreach ($f in @(Get-ChildItem -LiteralPath (G $rest[0]) -Filter $rest[1] -File)) {
                    if ($known -contains (Get-Sha $f.FullName)) { Remove-Retired $f.FullName }
                }
                Remove-Empty (G $rest[0])
            }
            "file" { Remove-Retired (G $rest[0]) }
            "hud-files" {
                # The file-based HUD fixes of hud 2.x, put back from their backups.
                $hf = Join-Path $here "retire\hud-files.py"
                if ($Py.Count -and (Test-Path -LiteralPath $hf)) {
                    $ErrorActionPreference = "Continue"
                    try { & $Py[0] @(@($Py | Select-Object -Skip 1)) $hf $GameDir 2>&1 | ForEach-Object { Say "  $_" } } catch { }
                    $ErrorActionPreference = "Stop"
                }
            }
            "chain-hash" {
                $f = G $rest[0]
                if ((Test-Path -LiteralPath $f -PathType Leaf) -and ((Get-Sha $f) -eq $rest[1])) {
                    Remove-Retired $f; Remove-ManifestRecord $rest[0]
                }
            }
            "chain-marker" {
                $f = G $rest[0]; $marker = ($rest | Select-Object -Skip 1) -join " "
                if ((Test-Path -LiteralPath $f -PathType Leaf) -and (Select-String -LiteralPath $f -Pattern $marker -SimpleMatch -Quiet)) {
                    Remove-Retired $f
                }
            }
            default { }   # bloom (the bloom step's), and kinds a newer table adds
        }
    }
}

# Packages before 13.0.0 put a bloom preset in for ReShade (A2Bloom.ini, and a copy as
# ReShadePreset.ini when the player had none); Render3D.asi blooms the 3D view itself
# now. The preset goes only while it is still that copy; ReShade itself is the player's.
function Remove-OldBloom {
    $ours = G "A2Bloom.ini"
    if (-not (Test-Path -LiteralPath $ours)) { return }
    $preset = G "ReShadePreset.ini"
    if ((Test-Path -LiteralPath $preset) -and (Get-Sha $preset) -eq (Get-Sha $ours)) {
        Remove-Item -LiteralPath $preset
    }
    Remove-Item -LiteralPath $ours
    Say "  removed the old bloom preset (A2Bloom.ini)"
}

