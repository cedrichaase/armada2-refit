function Merge-Ini([string]$shipped, [string]$installed, $upgrades, $retired = @()) {
    $label = Split-Path -Leaf $installed
    $secRe = '^\s*\[([^\]]+)\]'
    $keyRe = '^\s*(\w+)\s*=\s*(.*?)\s*$'
    $ship = @([IO.File]::ReadAllLines($shipped))
    $lines = New-Object Collections.Generic.List[string]
    foreach ($l in [IO.File]::ReadAllLines($installed)) { $lines.Add($l) }
    # "section|key" -> (line index, value), of the lines that are not comments
    function Get-IniValues($ls) {
        $out = @{}; $cur = $null
        for ($i = 0; $i -lt $ls.Count; $i++) {
            $l = $ls[$i]
            if ($l -match $secRe) { $cur = $Matches[1].ToLower(); continue }
            if ($null -ne $cur -and -not $l.TrimStart().StartsWith(";") -and $l -match $keyRe) {
                $out["$cur|$($Matches[1].ToLower())"] = @($i, $Matches[2])
            }
        }
        $out
    }
    $shipVals = Get-IniValues $ship
    $haveVals = Get-IniValues $lines
    # The defaults upgrade, before any key is added.
    $dsec = $null
    foreach ($k in $shipVals.Keys) { if ($k.EndsWith("|defaults")) { $dsec = $k.Split("|")[0]; break } }
    $shipN = 1; $haveN = 1
    if ($dsec -and $shipVals.ContainsKey("$dsec|defaults") -and $shipVals["$dsec|defaults"][1]) { $shipN = [int]$shipVals["$dsec|defaults"][1] }
    if ($dsec -and $haveVals.ContainsKey("$dsec|defaults") -and $haveVals["$dsec|defaults"][1]) { $haveN = [int]$haveVals["$dsec|defaults"][1] }
    foreach ($u in $upgrades) {
        $d, $n, $s, $k, $old = $u
        if ($d -ne $dsec -or -not ($haveN -lt $n -and $n -le $shipN)) { continue }
        $sk = "$s|$k"
        if (-not ($haveVals.ContainsKey($sk) -and $shipVals.ContainsKey($sk))) { continue }
        $i, $v = $haveVals[$sk]; $new = $shipVals[$sk][1]
        if ($v -ceq $old -and $v -cne $new) {
            $null = $lines[$i] -match $keyRe; $name = $Matches[1]
            $lines[$i] = "$name=$new"
            Say "  ${label}: [$s] $name $v -> $new (defaults $n)"
        }
    }
    foreach ($r in $retired) {
        $s, $k, $old = $r
        $sk = "$s|$k"
        if (-not ($haveVals.ContainsKey($sk) -and $shipVals.ContainsKey($sk))) { continue }
        $i, $v = $haveVals[$sk]; $new = $shipVals[$sk][1]
        if ($v -ceq $old -and $v -cne $new) {
            $null = $lines[$i] -match $keyRe; $name = $Matches[1]
            $lines[$i] = "$name=$new"
            Say "  ${label}: [$s] $name $v -> $new"
        }
    }
    # Display8.ini's Defaults 3 (tools/ini-merge.py, display8_defaults3): Mode and Real go,
    # `d3d9` goes from Backend= (nothing left: the shipped value), and a marked dxvk.conf's
    # sampler keys go into [Samplers] where the player set none (the shipped line the add
    # step below writes is replaced by the carried value).
    if ($dsec -eq "display8" -and $haveN -lt 3 -and 3 -le $shipN) {
        $gone = @()
        foreach ($k in "mode", "real") {
            if ($haveVals.ContainsKey("display8|$k")) {
                $i = $haveVals["display8|$k"][0]
                $null = $lines[$i] -match $keyRe
                Say "  ${label}: [display8] $($Matches[1]) dropped (defaults 3)"
                $gone += $i
            }
        }
        if ($haveVals.ContainsKey("display8|backend")) {
            $i, $v = $haveVals["display8|backend"]
            $toks = @($v -split "," | ForEach-Object { $_.Trim() } | Where-Object { $_ })
            $kept = @($toks | Where-Object { $_.ToLower() -ne "d3d9" })
            if ($kept.Count -ne $toks.Count) {
                $nv = if ($kept.Count) { $kept -join "," } elseif ($shipVals.ContainsKey("display8|backend")) { $shipVals["display8|backend"][1] } else { "auto" }
                $null = $lines[$i] -match $keyRe
                $lines[$i] = "$($Matches[1])=$nv"
                Say "  ${label}: [display8] Backend $v -> $nv (defaults 3)"
            }
        }
        $dxvk = Join-Path (Split-Path -Parent $installed) "dxvk.conf"
        if (Test-Path -LiteralPath $dxvk) {
            $marked = $false; $conf = @{}
            foreach ($dl in [IO.File]::ReadAllLines($dxvk)) {
                if ($dl.Trim() -ceq "# generated by tools/renderer-config.sh") { $marked = $true }
                elseif (-not $dl.TrimStart().StartsWith("#") -and $dl -match '^\s*([\w.]+)\s*=\s*(\S+)') { $conf[$Matches[1].ToLower()] = $Matches[2] }
            }
            if ($marked) {
                foreach ($pair in @(@("d3d9.sampleranisotropy", "anisotropy"), @("d3d9.samplerlodbias", "lodbias"), @("d3d9.clampnegativelodbias", "clampnegativelodbias"))) {
                    if (-not $conf.ContainsKey($pair[0])) { continue }
                    $key = $pair[1]; $v = $conf[$pair[0]]
                    if ($key -eq "clampnegativelodbias") { if ($v -ieq "true") { $v = "1" } elseif ($v -ieq "false") { $v = "0" } }
                    $sk = "samplers|$key"
                    $shipv = if ($shipVals.ContainsKey($sk)) { $shipVals[$sk][1] } else { "auto" }
                    $num = $v -match '^-?[0-9.]+$' -and $shipv -match '^-?[0-9.]+$'
                    if ($(if ($num) { [double]$v -eq [double]$shipv } else { $v -ieq $shipv })) { continue }
                    if ($haveVals.ContainsKey($sk)) {
                        if ($haveVals[$sk][1] -ine "auto") { continue }
                        $i = $haveVals[$sk][0]
                        $null = $lines[$i] -match $keyRe
                        $lines[$i] = "$($Matches[1])=$v"
                    } elseif ($shipVals.ContainsKey($sk)) {
                        $i = $shipVals[$sk][0]
                        $null = $ship[$i] -match $keyRe
                        $ship[$i] = "$($Matches[1])=$v"
                    }
                    Say "  ${label}: [samplers] $key -> $v (from dxvk.conf, defaults 3)"
                }
            }
        }
        foreach ($i in ($gone | Sort-Object -Descending)) { $lines.RemoveAt($i) }
        $haveVals = Get-IniValues $lines
    }
    if ($dsec -and $haveVals.ContainsKey("$dsec|defaults") -and $haveN -lt $shipN) {
        $i = $haveVals["$dsec|defaults"][0]
        $null = $lines[$i] -match $keyRe
        $lines[$i] = "$($Matches[1])=$shipN"
    }
    # Every key the player lacks, after the last line of its section (or the section
    # added at the end).
    $order = New-Object Collections.Generic.List[string]; $body = @{}; $head = @{}; $cur = $null
    foreach ($l in $ship) {
        if ($l -match $secRe) {
            $cur = $Matches[1].ToLower()
            if (-not $body.ContainsKey($cur)) { $order.Add($cur); $body[$cur] = New-Object Collections.Generic.List[string]; $head[$cur] = $l }
            continue
        }
        if ($null -ne $cur -and $l -match '^(\w+)=') { $body[$cur].Add($l) }
    }
    $haveKeys = @{}; $cur = $null
    foreach ($l in $lines) {
        if ($l -match $secRe) { $cur = $Matches[1].ToLower(); if (-not $haveKeys.ContainsKey($cur)) { $haveKeys[$cur] = @{} }; continue }
        if ($null -ne $cur -and -not $l.TrimStart().StartsWith(";") -and $l -match $keyRe) { $haveKeys[$cur][$Matches[1].ToLower()] = 1 }
    }
    foreach ($s in $order) {
        $missing = @($body[$s] | Where-Object { -not ($haveKeys.ContainsKey($s) -and $haveKeys[$s].ContainsKey(($_ -split "=")[0].ToLower())) })
        if (-not $missing.Count) { continue }
        if ($haveKeys.ContainsKey($s)) {
            $at = $lines.Count; $c = $null
            for ($i = 0; $i -lt $lines.Count; $i++) {
                if ($lines[$i] -match $secRe) { if ($c -eq $s) { $at = $i; break }; $c = $Matches[1].ToLower() }
            }
            while ($at -gt 0 -and -not $lines[$at - 1].Trim()) { $at-- }
            $lines.InsertRange($at, [string[]]$missing)
        } else {
            $lines.Add(""); $lines.Add($head[$s]); $lines.AddRange([string[]]$missing)
        }
    }
    # Nothing to add (line ends aside): the player's file stays byte for byte.
    $before = (@([IO.File]::ReadAllLines($installed)) -join "`n")
    if ($before -ne ($lines -join "`n")) { [IO.File]::WriteAllText($installed, (($lines -join "`n") + "`n")) }
}

# One key of an installed .ini: Get-IniKey returns its value (a ; comment dropped) or $null;
# Set-IniKey replaces the key's first line, else adds it after the last line of its section
# (the section is added at the end if missing); Remove-IniKey removes every line of the key.
function Find-IniKey($lines, [string]$section, [string]$key) {
    $cur = $null; $first = -1; $last = -1; $insec = $false; $hits = @()
    for ($i = 0; $i -lt $lines.Count; $i++) {
        $t = $lines[$i].Trim()
        if ($t.StartsWith("[")) {
            $cur = ($t.TrimStart("[") -split "\]")[0].Trim().ToLower()
            if ($cur -eq $section.ToLower()) { $insec = $true; $last = $i }
            continue
        }
        if ($cur -ne $section.ToLower()) { continue }
        if ($t) { $last = $i }
        if (-not $t.StartsWith(";") -and -not $t.StartsWith("#") -and $t.Contains("=")) {
            if (($t -split "=", 2)[0].Trim().ToLower() -eq $key.ToLower()) {
                if ($first -lt 0) { $first = $i }
                $hits += $i
            }
        }
    }
    @{ First = $first; Last = $last; Insec = $insec; Hits = $hits }
}
function Get-IniKey([string]$file, [string]$section, [string]$key) {
    $lines = @([IO.File]::ReadAllLines($file))
    $f = Find-IniKey $lines $section $key
    if ($f.First -lt 0) { return $null }
    (($lines[$f.First] -split "=", 2)[1] -split ";")[0].Trim()
}
function Set-IniKey([string]$file, [string]$section, [string]$key, [string]$value) {
    $lines = New-Object Collections.Generic.List[string]
    foreach ($l in [IO.File]::ReadAllLines($file)) { $lines.Add($l) }
    $f = Find-IniKey $lines $section $key
    if ($f.First -ge 0) { $lines[$f.First] = (($lines[$f.First] -split "=", 2)[0]) + "=" + $value }
    elseif ($f.Insec) { $lines.Insert($f.Last + 1, "$key=$value") }
    else { $lines.Add(""); $lines.Add("[$section]"); $lines.Add("$key=$value") }
    [IO.File]::WriteAllText($file, (($lines -join "`n") + "`n"))
}
function Remove-IniKey([string]$file, [string]$section, [string]$key) {
    $lines = New-Object Collections.Generic.List[string]
    foreach ($l in [IO.File]::ReadAllLines($file)) { $lines.Add($l) }
    $f = Find-IniKey $lines $section $key
    if (-not $f.Hits.Count) { return }
    for ($j = $f.Hits.Count - 1; $j -ge 0; $j--) { $lines.RemoveAt($f.Hits[$j]) }
    [IO.File]::WriteAllText($file, (($lines -join "`n") + "`n"))
}
# Settings that moved from one file to another (moved.txt, baked by package.sh from the
# settings tables): a value other than the new default goes to the new key, and the old key
# is removed either way -- tools/settings/move-keys.py's job in the repository's ./install.
function Invoke-Moved {
    $mf = Join-Path $here "moved.txt"
    if (-not (Test-Path -LiteralPath $mf)) { return }
    foreach ($l in Get-Content -LiteralPath $mf) {
        if (-not $l.Trim()) { continue }
        $ff, $fs, $fk, $tf, $ts, $tk, $def = $l -split "`t"
        if (-not (Test-Path -LiteralPath (G $ff))) { continue }
        $v = Get-IniKey (G $ff) $fs $fk
        if ($null -eq $v) { continue }
        # The one rule (tools/settings/README.md, "Moved keys"): a new key the player set
        # (present, not empty, not the default) wins; else the old value moves if it is not
        # the default; the old key goes either way.
        $nv = $null
        if (Test-Path -LiteralPath (G $tf)) { $nv = Get-IniKey (G $tf) $ts $tk }
        if ($nv -and ($nv.ToLower() -ne "$def".ToLower())) {
            Say "  $ff [$fs] $fk=$v dropped ($tf [$ts] $tk=$nv is set already)"
        } elseif ($v.ToLower() -ne "$def".ToLower()) {
            if (-not (Test-Path -LiteralPath (G $tf))) { Say "  $tf is not there; $ff [$fs] $fk=$v stays"; continue }
            Set-IniKey (G $tf) $ts $tk $v
            Say "  moved $ff [$fs] $fk=$v to $tf [$ts] $tk"
        }
        Remove-IniKey (G $ff) $fs $fk
    }
}

