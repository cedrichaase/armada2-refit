if ($Uninstall) {
    Step uninstall "taking the mod out"
    $Py = @(Find-Python)
    Remove-Display8 -All
    foreach ($n in "Render3D", "UI", "QOL", "QOLRules", "Online") {
        foreach ($e in ".asi", ".ini", ".log") { Remove-Item -LiteralPath (G "$n$e") -ErrorAction SilentlyContinue }
    }
    Remove-Item -LiteralPath (G "armada2-refit-layers.txt") -ErrorAction SilentlyContinue   # the remembered choice
    Invoke-Retire
    Remove-Recipes
    if (Test-Path -LiteralPath (Join-Path $here "models")) {
        if ($Py.Count) { Say "  the models back to stock:"; Invoke-Sods "--revert" }
        else { Say "  the models left as they are: needs Python 3 (py or python) to put them back" }
    }
    Remove-Proxy
    # The prerequisites, newest record first; a file changed since is left, and said so.
    if (Test-Path -LiteralPath $Manifest) {
        $records = @(Get-Content -LiteralPath $Manifest)
        [array]::Reverse($records)
        foreach ($r in $records) {
            if (-not $r.Trim()) { continue }
            $f, $sum = $r.Trim() -split " "
            if (-not (Test-Path -LiteralPath (G $f))) { continue }
            if ((Get-Sha (G $f)) -ne $sum) { Say "  left ${f}: it changed since it was installed"; continue }
            Remove-Item -LiteralPath (G $f)
        }
        Remove-Item -LiteralPath $Manifest
    }
    # What an install replaced, back where it took it out: GOG's d3d8.dll (kept as
    # d3d8.dll.gog-backup), and what installs before 15.6.0 kept as .a2chain-backup.
    foreach ($f in "d3d8.dll", "d3d9.dll") {
        if (Test-Path -LiteralPath (G $f)) { continue }
        if ($f -eq "d3d8.dll" -and (Test-Path -LiteralPath (G "d3d8.dll.gog-backup"))) {
            Move-Item -LiteralPath (G "d3d8.dll.gog-backup") (G "d3d8.dll")
        } elseif (Test-Path -LiteralPath (G "$f$ChainBackup")) {
            Move-Item -LiteralPath (G "$f$ChainBackup") (G $f)
        } elseif ($f -eq "d3d8.dll" -and (Test-Path -LiteralPath (G "d3d8.dll.a2display-backup"))) {
            Move-Item -LiteralPath (G "d3d8.dll.a2display-backup") (G "d3d8.dll")
        }
    }
    Remove-Item -LiteralPath (G "d3d8.dll.a2display-backup") -ErrorAction SilentlyContinue
    Remove-OldBloom
    Say "uninstalled from $GameDir"
    exit 0
}

# A package file as SHA256SUMS names it, the Windows way (layers\legacy\Menus.asi).
function Rel([string]$p) {
    if ($p.StartsWith($here + "\")) { $p = $p.Substring($here.Length + 1) }
    $p -replace "/", "\"
}
# The file's sha256, read with .NET so that each way it can fail throws: gone
# (FileNotFoundException), held open (IOException), refused (UnauthorizedAccessException).
function Read-Sha([string]$f) {
    $s = [IO.File]::Open($f, "Open", "Read", "Read")
    try {
        $h = [Security.Cryptography.SHA256]::Create()
        ([BitConverter]::ToString($h.ComputeHash($s)) -replace "-", "")
    } finally { $s.Dispose() }
}
function Test-Readable([string]$f) { try { [IO.File]::Open($f, "Open", "Read", "Read").Dispose(); $true } catch { $false } }

# Every file checked before anything is said: an antivirus seldom takes only one.
Step verify "checking the package"
$missing = @(); $locked = @(); $damaged = @()
foreach ($line in Get-Content -LiteralPath (Join-Path $here "SHA256SUMS")) {
    if (-not $line.Trim()) { continue }
    $sum, $file = $line -split "\s+\*?", 2
    $f = Join-Path $here $file
    if (-not (Test-Path -LiteralPath $f -PathType Leaf)) { $missing += Rel $file; continue }
    try { $h = Read-Sha $f } catch { $locked += Rel $file; continue }
    if ($h -ne $sum) { $damaged += Rel $file }
}
if ($missing.Count -or $locked.Count) {
    if ($env:A2_PROGRESS -eq "1") {
        foreach ($p in $damaged) { Say "::error damaged $p" }
        foreach ($p in $missing) { Say "::error av-missing $p" }
        foreach ($p in $locked) { Say "::error av-locked $p" }
    }
    $gone = @($missing) + @($locked)
    $what = "could not be read"
    if ($missing.Count) { $what = if ($locked.Count) { "are missing or could not be read" } else { "are missing" } }
    if ($gone.Count -eq 1) { $what = $what -replace "^are", "is" }
    throw ("$($gone -join ', ') from the package $what. An antivirus has most likely " +
        "quarantined or locked $(if ($gone.Count -eq 1) { 'it' } else { 'them' }). " + (Av-Advice))
}
if ($damaged.Count) {
    Stop-With damaged $damaged ("the package is damaged: $($damaged -join ', ') " +
        "$(if ($damaged.Count -eq 1) { 'does' } else { 'do' }) not match SHA256SUMS. Download it again. " +
        "An antivirus that cleans or cuts files in place can do this too: look in its quarantine and history.")
}
Say "installing into $GameDir"

