#!/usr/bin/env bash
# Build Render3D.asi -- a 32-bit Windows DLL written in no_std Rust, cross-compiled on
# Linux with rustup's i686-pc-windows-msvc target and lld-link (.cargo/config.toml).
#
#   build.sh                     every module: build/Render3D.asi, the DLL that ships
#   build.sh --features LIST     only the modules in LIST (comma-separated: hulls,sky),
#                                into build/subset/Render3D.asi with a target directory
#                                of its own; a source build for modders and the bench
#                                (README.md, "Crates")
#
# Shaders first, crate by crate (core/ and each mods/<m>/): each <crate>/shaders/<name>.hlsl
# names its entry points on its first line,
#   // entries: <entry>:<profile>:<SYMBOL> ...
# and is compiled by tools/shaderc/hlsl-rs.sh into <crate>/src/shaders/<name>.rs, Direct3D 9
# bytecode from vkd3d, <name>_spv.rs, SPIR-V from dxc, and <name>_dxil.rs, DXIL from the
# pinned dxc (committed, with stamps, so a machine without the compilers builds as long
# as they are current), with --fix: Windows' own Direct3D 9 refuses vkd3d's bytecode as
# it is (README.md, "Shaders on Windows"). A module's shaders include the core's headers
# (core/shaders/*.hlsli), which its stamps cover (--headers). <crate>/src/shaders/mod.rs
# lists them and is written here too. Every crate's shaders are compiled whatever the
# features, so the committed files stay current.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cargo="${CARGO:-$HOME/.cargo/bin/cargo}"   # rustup's: a distribution cargo has no i686-pc-windows-msvc
[ -x "$cargo" ] || cargo=$(command -v cargo || true)
[ -x "$cargo" ] || { echo "render3d: cargo not found (install rustup, then: rustup target add i686-pc-windows-msvc)" >&2; exit 1; }

features=""
subset=0
while [ $# -gt 0 ]; do
    case $1 in
        --features) [ $# -ge 2 ] || { echo "render3d/build.sh: --features needs a list" >&2; exit 2; }
                    features=$2; subset=1; shift 2 ;;
        --features=*) features=${1#--features=}; subset=1; shift ;;
        *) echo "render3d/build.sh: unknown argument $1 (build.sh [--features hulls,sky])" >&2; exit 2 ;;
    esac
done

# Temp files of this run's own, beside their targets so each mv is a rename: several
# installs of one checkout can run at once (a2film --jobs, a2test -j).
new="" asi=""
trap 'rm -f ${new:+"$new"} ${asi:+"$asi"}' EXIT
for crate in "$here/core" "$here"/mods/*; do
    [ -d "$crate/shaders" ] || continue
    headers=()
    [ "$crate" = "$here/core" ] || headers=(--headers "$here/core/shaders")
    mods=""
    for f in "$crate"/shaders/*.hlsl; do
        name=$(basename "$f" .hlsl)
        entries=$(sed -n '1s#^// entries:##p' "$f")
        [ -n "$entries" ] || { echo "render3d: $f has no '// entries:' first line" >&2; exit 1; }
        # shellcheck disable=SC2086
        "$here/../tools/shaderc/hlsl-rs.sh" --fix "${headers[@]}" "$crate/src/shaders/$name.rs" "$f" $entries
        mods="$mods$name ${name}_spv ${name}_dxil "
    done
    new=$(mktemp "$crate/src/shaders/.mod.rs.XXXXXX")
    {
        echo "//! Shader bytecode, generated by build.sh from shaders/*.hlsl -- do not edit."
        for m in $mods; do echo "pub mod $m;"; done
    } > "$new"
    if cmp -s "$new" "$crate/src/shaders/mod.rs"; then
        rm "$new"
    else
        chmod 644 "$new"
        mv "$new" "$crate/src/shaders/mod.rs"
    fi
    new=""
done

target="$here/target" out="$here/build" feat=()
if [ "$subset" = 1 ]; then
    target="$here/target-subset" out="$here/build/subset"
    feat=(--no-default-features ${features:+--features "$features"})
fi
env -C "$here" "$cargo" build --release --quiet --target-dir "$target" "${feat[@]}"
mkdir -p "$out"
asi=$(mktemp "$out/.Render3D.asi.XXXXXX")
cp "$target/i686-pc-windows-msvc/release/render3d.dll" "$asi"
chmod 644 "$asi"
mv "$asi" "$out/Render3D.asi"
asi=""
if [ "$subset" = 1 ]; then
    echo "built $out/Render3D.asi (modules: ${features:-none})"
else
    echo "built $out/Render3D.asi"
fi
