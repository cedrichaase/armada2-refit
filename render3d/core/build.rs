// Builds render3d's content into the core (README.md, "Content sets"): every `.ini`
// under `render3d/content/` (the recipes by kind, and each set's tables in
// `content/sets/<set>/<module>.ini`) as `FILES`, (path relative to `content/` with `/`,
// its text by `include_str!`), sorted by path. A new set is a new folder: nothing in
// the code names one.
use std::{env, fs, path::Path, path::PathBuf};

fn walk(dir: &Path, base: &Path, out: &mut Vec<(String, PathBuf)>) {
    let mut es: Vec<_> = fs::read_dir(dir).expect("render3d/content not readable").flatten().collect();
    es.sort_by_key(|e| e.file_name());
    for e in es {
        let p = e.path();
        if p.is_dir() {
            walk(&p, base, out);
        } else if p.extension().is_some_and(|x| x == "ini") {
            let rel = p.strip_prefix(base).unwrap().components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect::<Vec<_>>().join("/");
            out.push((rel, p.canonicalize().unwrap()));
        }
    }
}

fn main() {
    let here = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let content = here.join("../content").canonicalize().expect("render3d/content missing");
    println!("cargo:rerun-if-changed={}", content.display());
    let mut files = Vec::new();
    walk(&content, &content, &mut files);
    files.sort();
    let mut s = String::from("// generated by render3d/core/build.rs from render3d/content/\npub static FILES: &[(&str, &str)] = &[\n");
    for (rel, p) in &files {
        s.push_str(&format!("    ({:?}, include_str!({:?})),\n", rel, p.display().to_string()));
    }
    s.push_str("];\n");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("content_files.rs");
    fs::write(out, s).unwrap();
}
