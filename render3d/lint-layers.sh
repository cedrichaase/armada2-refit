#!/usr/bin/env bash
# The layer rules of render3d's sources (README.md, "Module interface", "Layers"):
#
#   1. engine   no address literal (0x400000..0x7fffff) and no `field*`/`rd` read outside
#               the engine glue: src/engine/** (core/engine/ once the crates are split)
#               and each module's src/mods/<m>/hooks.rs (and src/core_hooks.rs, the
#               registry that checks the sites it patches)
#   2. cross    no `crate::mods::<other>` path inside src/mods/<m>/
#   3. byname   no `running("..")` / `enabled("..")` in module code: ask a capability
#               (core_services), never a module by name
#   4. content  no string literal naming an ODF, SOD, sprite or texture (`*.odf`, `*.sod`,
#               `*.spr`, `*.tga`) outside src/mods/<m>/content.rs and render3d/content/
#               (advisory: never strict)
#
#   lint-layers.sh                    report: counts per rule and directory; exits 0
#   lint-layers.sh --list             report, with every hit as file:line
#   lint-layers.sh --strict DIR...    exit 1 on any hit of rules 1-3 under the DIRs
#                                     (paths relative to render3d/, e.g. src/mods/hulls)
#
# The generated shaders (src/shaders/) and generated settings tables are not read.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exec python3 - "$here" "$@" <<'PY'
import os, re, sys

here = sys.argv[1]
args = sys.argv[2:]
listing = '--list' in args
strict = []
if '--strict' in args:
    strict = [os.path.normpath(a) for a in args[args.index('--strict') + 1:] if not a.startswith('--')]
    if not strict:
        print('lint-layers.sh: --strict needs at least one directory', file=sys.stderr)
        sys.exit(2)

src = os.path.join(here, 'src')
GENERATED = re.compile(r'(//|/\*) generated by ')
ADDR = re.compile(r'\b0x0*([4-7][0-9a-fA-F]{5})\b')
FIELD = re.compile(r'(?<![\w.])(?:engine::)?(field|field_f32|field_u8|field_m34|field_v3|rd)\s*(::\s*<[^>]*>\s*)?\(')
CROSS = re.compile(r'crate::mods::([a-z_]+)')
BYNAME = re.compile(r'(?<![\w])(?:crate::mods::|mods::|super::)?(running|enabled)\s*\(\s*"')
CONTENT = re.compile(r'"[^"\n]*\.(odf|sod|spr|tga)"', re.I)


def strip_comments(line):
    # Comments (// and doc comments) are words, not code: an address named in a
    # sentence is allowed (CLAUDE.md, hard rule 9).
    out, i, q = [], 0, False
    while i < len(line):
        c = line[i]
        if c == '"' and (i == 0 or line[i - 1] != '\\'):
            q = not q
        if not q and line.startswith('//', i):
            break
        out.append(c)
        i += 1
    return ''.join(out)


def module_of(rel):
    p = rel.split(os.sep)
    if len(p) >= 3 and p[0] == 'src' and p[1] == 'mods':
        return p[2] if len(p) > 3 else None
    return None


def is_glue(rel):
    p = rel.split(os.sep)
    # core_hooks.rs is the hook registry itself: it reads the slots it patches.
    return (p[:2] == ['src', 'engine']) or rel == os.path.join('src', 'core_hooks.rs') or (len(p) == 4 and p[1] == 'mods' and p[3] == 'hooks.rs')


hits = {r: [] for r in ('engine', 'cross', 'byname', 'content')}
for d, dirs, files in os.walk(src):
    dirs[:] = sorted(x for x in dirs if not (d == src and x == 'shaders'))
    for f in sorted(files):
        if not f.endswith('.rs'):
            continue
        path = os.path.join(d, f)
        rel = os.path.relpath(path, here)
        text = open(path, encoding='utf-8', errors='replace').read()
        if GENERATED.match(text):
            continue
        m = module_of(rel)
        glue = is_glue(rel)
        for n, raw in enumerate(text.split('\n'), 1):
            line = strip_comments(raw)
            if not glue:
                for _ in ADDR.finditer(line):
                    hits['engine'].append((rel, n))
                for _ in FIELD.finditer(line):
                    hits['engine'].append((rel, n))
            if m is not None:
                for g in CROSS.finditer(line):
                    if g.group(1) != m:
                        hits['cross'].append((rel, n))
                if BYNAME.search(line):
                    hits['byname'].append((rel, n))
                if f != 'content.rs' and CONTENT.search(line):
                    hits['content'].append((rel, n))


def area(rel):
    p = rel.split(os.sep)
    if p[1] == 'mods' and len(p) > 3:
        return os.path.join('src', 'mods', p[2])
    if len(p) > 2:
        return os.path.join('src', p[1])
    return rel


names = {'engine': 'engine glue outside src/engine and hooks.rs', 'cross': 'crate::mods::<other> in a module',
         'byname': 'running/enabled by name in a module', 'content': 'content names outside content.rs (advisory)'}
total = 0
for r, hs in hits.items():
    by = {}
    for rel, n in hs:
        by.setdefault(area(rel), []).append((rel, n))
    print(f'{r:8} {len(hs):5}  {names[r]}')
    for a in sorted(by):
        print(f'           {len(by[a]):5}  {a}')
        if listing:
            for rel, n in by[a]:
                print(f'                  {rel}:{n}')
    if r != 'content':
        total += len(hs)
print(f'lint-layers.sh: {total} hits of rules 1-3 ({len(hits["content"])} advisory)')

if strict:
    bad = [(r, rel, n) for r in ('engine', 'cross', 'byname') for rel, n in hits[r]
           if any(rel == s or rel.startswith(s + os.sep) for s in strict)]
    for r, rel, n in bad:
        print(f'lint-layers.sh: {rel}:{n}: {names[r]}')
    sys.exit(1 if bad else 0)
PY
