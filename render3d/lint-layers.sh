#!/usr/bin/env bash
# The layer rules of render3d's sources (README.md, "Module interface", "Layers",
# "Crates"), over the core (core/src) and every module crate (mods/<m>/src):
#
#   1. engine   no address literal (0x400000..0x7fffff) and no `field*`/`rd` read outside
#               the engine glue: core/src/engine/** and each module's
#               mods/<m>/src/hooks.rs (and core/src/hooks.rs, the registry that checks
#               the sites it patches)
#   2. cross    no path into another module's crate (`r3d_<other>::`) inside
#               mods/<m>/, and no `r3d-<other>` dependency in its Cargo.toml: a module
#               depends on r3d-core alone
#   3. byname   no `running("..")` / `enabled("..")` in module code: ask a capability
#               (services), never a module by name
#   4. content  no string literal naming an ODF, SOD, sprite or texture (`*.odf`, `*.sod`,
#               `*.spr`, `*.tga`) outside mods/<m>/src/content.rs and render3d/content/
#               (advisory: never strict)
#
#   lint-layers.sh                    report: counts per rule and directory; exits 0
#   lint-layers.sh --list             report, with every hit as file:line
#   lint-layers.sh --strict DIR...    exit 1 on any hit of rules 1-3 under the DIRs
#                                     (paths relative to render3d/, e.g. mods/hulls)
#   ... --rules cross,byname          with --strict: only those rules (engine, cross, byname)
#
# CI holds every module crate (mods) and the core to rules 1-3 (the core's engine reads
# live in core/src/engine/**: phase 8e moved them there, with the addresses into the
# symbol profile).
#
# The generated shaders (src/shaders/) and generated settings tables are not read.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exec python3 - "$here" "$@" <<'PY'
import os, re, sys

here = sys.argv[1]
args = sys.argv[2:]
listing = '--list' in args
strict = []
rules = ('engine', 'cross', 'byname')
if '--rules' in args:
    rules = tuple(args[args.index('--rules') + 1].split(','))
if '--strict' in args:
    rest = args[args.index('--strict') + 1:]
    if '--rules' in rest:
        rest = rest[:rest.index('--rules')]
    strict = [os.path.normpath(a) for a in rest if not a.startswith('--')]
    if not strict:
        print('lint-layers.sh: --strict needs at least one directory', file=sys.stderr)
        sys.exit(2)

roots = [os.path.join(here, 'core', 'src')] + sorted(
    os.path.join(here, 'mods', m, 'src') for m in os.listdir(os.path.join(here, 'mods'))
    if os.path.isdir(os.path.join(here, 'mods', m, 'src')))
GENERATED = re.compile(r'(//|/\*) generated by ')
ADDR = re.compile(r'\b0x0*([4-7][0-9a-fA-F]{5})\b')
FIELD = re.compile(r'(?<![\w.])(?:engine::)?(field|field_f32|field_u8|field_m34|field_v3|rd)\s*(::\s*<[^>]*>\s*)?\(')
CROSS = re.compile(r'\br3d_([a-z_]+)::')
DEP = re.compile(r'^\s*r3d-([a-z_]+)\s*=', re.M)
BYNAME = re.compile(r'(?<![\w])(?:r3d_core::registry::|registry::)?(running|enabled)\s*\(\s*"')
CONTENT = re.compile(r'"[^"\n]*\.(odf|sod|spr|tga)"', re.I)


def strip_comments(line):
    # Comments (// and doc comments) are words, not code: an address named in a
    # sentence is allowed (CLAUDE.md, hard rule 9).
    out, i, q = [], 0, False
    while i < len(line):
        c = line[i]
        if c == '"' and (i == 0 or line[i - 1] != '\\'):
            q = not q
        if not q and line.startswith('//', i):
            break
        out.append(c)
        i += 1
    return ''.join(out)


def module_of(rel):
    p = rel.split(os.sep)
    if len(p) >= 4 and p[0] == 'mods' and p[2] == 'src':
        return p[1]
    return None


def is_glue(rel):
    p = rel.split(os.sep)
    # core/src/hooks.rs is the hook registry itself: it reads the slots it patches.
    return (p[:3] == ['core', 'src', 'engine']) or rel == os.path.join('core', 'src', 'hooks.rs') \
        or (len(p) == 4 and p[0] == 'mods' and p[2] == 'src' and p[3] == 'hooks.rs')


hits = {r: [] for r in ('engine', 'cross', 'byname', 'content')}
for d, dirs, files in (w for src in roots for w in os.walk(src)):
    dirs[:] = sorted(x for x in dirs if x != 'shaders' or os.path.basename(d) != 'src')
    for f in sorted(files):
        if not f.endswith('.rs'):
            continue
        path = os.path.join(d, f)
        rel = os.path.relpath(path, here)
        text = open(path, encoding='utf-8', errors='replace').read()
        if GENERATED.match(text):
            continue
        m = module_of(rel)
        glue = is_glue(rel)
        for n, raw in enumerate(text.split('\n'), 1):
            line = strip_comments(raw)
            if not glue:
                for _ in ADDR.finditer(line):
                    hits['engine'].append((rel, n))
                for _ in FIELD.finditer(line):
                    hits['engine'].append((rel, n))
            if m is not None:
                for g in CROSS.finditer(line):
                    if g.group(1) not in (m, 'core'):
                        hits['cross'].append((rel, n))
                if BYNAME.search(line):
                    hits['byname'].append((rel, n))
                if f != 'content.rs' and CONTENT.search(line):
                    hits['content'].append((rel, n))

# A module's crate depends on r3d-core and on no other module.
for m in sorted(os.listdir(os.path.join(here, 'mods'))):
    toml = os.path.join(here, 'mods', m, 'Cargo.toml')
    if os.path.isfile(toml):
        text = open(toml, encoding='utf-8').read()
        for n, raw in enumerate(text.split('\n'), 1):
            g = DEP.match(raw)
            if g and g.group(1) not in ('core', m):
                hits['cross'].append((os.path.relpath(toml, here), n))


def area(rel):
    p = rel.split(os.sep)
    if p[0] == 'mods' and len(p) > 2:
        return os.path.join('mods', p[1])
    if p[:2] == ['core', 'src'] and len(p) > 3:
        return os.path.join('core', 'src', p[2])
    return rel


names = {'engine': 'engine glue outside core/src/engine and hooks.rs', 'cross': 'another module\'s crate in a module',
         'byname': 'running/enabled by name in a module', 'content': 'content names outside content.rs (advisory)'}
total = 0
for r, hs in hits.items():
    by = {}
    for rel, n in hs:
        by.setdefault(area(rel), []).append((rel, n))
    print(f'{r:8} {len(hs):5}  {names[r]}')
    for a in sorted(by):
        print(f'           {len(by[a]):5}  {a}')
        if listing:
            for rel, n in by[a]:
                print(f'                  {rel}:{n}')
    if r != 'content':
        total += len(hs)
print(f'lint-layers.sh: {total} hits of rules 1-3 ({len(hits["content"])} advisory)')

if strict:
    bad = [(r, rel, n) for r in rules for rel, n in hits[r]
           if any(rel == s or rel.startswith(s + os.sep) for s in strict)]
    for r, rel, n in bad:
        print(f'lint-layers.sh: {rel}:{n}: {names[r]}')
    sys.exit(1 if bad else 0)
PY
