#!/usr/bin/env bash
# Build d3d8.dll (Display8) -- a 32-bit Windows DLL written in no_std Rust,
# cross-compiled on Linux with rustup's i686-pc-windows-msvc target and lld-link
# (.cargo/config.toml), as render3d/build.sh builds Render3D.asi.
#
# Shaders first, as ui/build.sh does: each shaders/<name>.hlsl names its entry points
# on its first line and is compiled by render3d's hlsl-rs.sh into src/shaders/<name>.rs
# (Direct3D 9 bytecode), <name>_spv.rs (SPIR-V) and <name>_dxil.rs (DXIL), committed
# with stamps.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cargo="${CARGO:-$HOME/.cargo/bin/cargo}"   # rustup's: a distribution cargo has no i686-pc-windows-msvc
[ -x "$cargo" ] || cargo=$(command -v cargo || true)
[ -x "$cargo" ] || { echo "display: cargo not found (install rustup, then: rustup target add i686-pc-windows-msvc)" >&2; exit 1; }

mkdir -p "$here/src/shaders"
mods=""
for f in "$here"/shaders/*.hlsl; do
    [ -e "$f" ] || continue
    name=$(basename "$f" .hlsl)
    entries=$(sed -n '1s#^// entries:##p' "$f")
    [ -n "$entries" ] || { echo "display: $f has no '// entries:' first line" >&2; exit 1; }
    # shellcheck disable=SC2086
    "$here/../render3d/hlsl-rs.sh" --fix "$here/src/shaders/$name.rs" "$f" $entries
    mods="$mods$name ${name}_spv ${name}_dxil "
done
# Temp files of this run's own, beside their targets so each mv is a rename: several
# installs of one checkout can run at once (a2test -j).
new=$(mktemp "$here/src/shaders/.mod.rs.XXXXXX")
dll=""
trap 'rm -f "$new" ${dll:+"$dll"}' EXIT
{
    echo "//! Shader bytecode, generated by build.sh from shaders/*.hlsl -- do not edit."
    for m in $mods; do echo "pub mod $m;"; done
} > "$new"
if cmp -s "$new" "$here/src/shaders/mod.rs"; then
    rm "$new"
else
    chmod 644 "$new"
    mv "$new" "$here/src/shaders/mod.rs"
fi

env -C "$here" "$cargo" build --release --quiet
mkdir -p "$here/build"
dll=$(mktemp "$here/build/.d3d8.dll.XXXXXX")
cp "$here/target/i686-pc-windows-msvc/release/display.dll" "$dll"
chmod 644 "$dll"
mv "$dll" "$here/build/d3d8.dll"
echo "built $here/build/d3d8.dll"
