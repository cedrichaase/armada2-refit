#!/usr/bin/env bash
# Build UI.asi -- a 32-bit Windows DLL written in no_std Rust, cross-compiled on Linux
# with rustup's i686-pc-windows-msvc target and lld-link (.cargo/config.toml), as
# render3d is.
#
# Shaders first: each shaders/<name>.hlsl names its entry points on its first line,
#   // entries: <entry>:<profile>:<SYMBOL> ...
# and is compiled by render3d's hlsl-rs.sh into src/shaders/<name>.rs (committed, with a
# stamp, so a machine without vkd3d-compiler builds as long as they are current), with
# --fix: Windows' own Direct3D 9 refuses vkd3d's bytecode as it is (render3d/README.md,
# "Shaders on Windows").
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cargo="${CARGO:-$HOME/.cargo/bin/cargo}"   # rustup's: a distribution cargo has no i686-pc-windows-msvc
[ -x "$cargo" ] || cargo=$(command -v cargo || true)
[ -x "$cargo" ] || { echo "ui: cargo not found (install rustup, then: rustup target add i686-pc-windows-msvc)" >&2; exit 1; }

mkdir -p "$here/src/shaders"
mods=""
for f in "$here"/shaders/*.hlsl; do
    [ -e "$f" ] || continue
    name=$(basename "$f" .hlsl)
    entries=$(sed -n '1s#^// entries:##p' "$f")
    [ -n "$entries" ] || { echo "ui: $f has no '// entries:' first line" >&2; exit 1; }
    # shellcheck disable=SC2086
    "$here/../render3d/hlsl-rs.sh" --fix "$here/src/shaders/$name.rs" "$f" $entries
    mods="$mods$name "
done
{
    echo "//! Shader bytecode, generated by build.sh from shaders/*.hlsl -- do not edit."
    for m in $mods; do echo "pub mod $m;"; done
} > "$here/src/shaders/mod.rs.new"
if cmp -s "$here/src/shaders/mod.rs.new" "$here/src/shaders/mod.rs"; then
    rm "$here/src/shaders/mod.rs.new"
else
    mv "$here/src/shaders/mod.rs.new" "$here/src/shaders/mod.rs"
fi

env -C "$here" "$cargo" build --release --quiet
mkdir -p "$here/build"
cp "$here/target/i686-pc-windows-msvc/release/ui.dll" "$here/build/UI.asi"
echo "built $here/build/UI.asi"
