#!/usr/bin/env bash
# Build UI.asi -- a 32-bit Windows DLL written in no_std Rust, cross-compiled on Linux
# with rustup's i686-pc-windows-msvc target and lld-link (.cargo/config.toml), as
# render3d is.
#
# Shaders first: each shaders/<name>.hlsl names its entry points on its first line,
#   // entries: <entry>:<profile>:<SYMBOL> ...
# and is compiled by render3d's hlsl-rs.sh into src/shaders/<name>.rs, Direct3D 9
# bytecode from vkd3d, src/shaders/<name>_spv.rs, SPIR-V from dxc, and
# src/shaders/<name>_dxil.rs, DXIL from the pinned dxc (committed, with stamps, so a
# machine without the compilers builds as long as they are current), with
# --fix: Windows' own Direct3D 9 refuses vkd3d's bytecode as it is (render3d/README.md,
# "Shaders on Windows").
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cargo="${CARGO:-$HOME/.cargo/bin/cargo}"   # rustup's: a distribution cargo has no i686-pc-windows-msvc
[ -x "$cargo" ] || cargo=$(command -v cargo || true)
[ -x "$cargo" ] || { echo "ui: cargo not found (install rustup, then: rustup target add i686-pc-windows-msvc)" >&2; exit 1; }

mkdir -p "$here/src/shaders"
mods=""
for f in "$here"/shaders/*.hlsl; do
    [ -e "$f" ] || continue
    name=$(basename "$f" .hlsl)
    entries=$(sed -n '1s#^// entries:##p' "$f")
    [ -n "$entries" ] || { echo "ui: $f has no '// entries:' first line" >&2; exit 1; }
    # shellcheck disable=SC2086
    "$here/../tools/shaderc/hlsl-rs.sh" --fix "$here/src/shaders/$name.rs" "$f" $entries
    mods="$mods$name ${name}_spv ${name}_dxil "
done
# Temp files of this run's own, beside their targets so each mv is a rename: several
# installs of one checkout can run at once (a2test -j). A fixed name (mod.rs.new) let
# one run move the other's file away under it.
new=$(mktemp "$here/src/shaders/.mod.rs.XXXXXX")
asi=""
trap 'rm -f "$new" ${asi:+"$asi"}' EXIT
{
    echo "//! Shader bytecode, generated by build.sh from shaders/*.hlsl -- do not edit."
    for m in $mods; do echo "pub mod $m;"; done
} > "$new"
if cmp -s "$new" "$here/src/shaders/mod.rs"; then
    rm "$new"
else
    chmod 644 "$new"
    mv "$new" "$here/src/shaders/mod.rs"
fi

# Cargo locks the target directory: a second build of the tree waits for the first and
# finds it fresh.
env -C "$here" "$cargo" build --release --quiet
mkdir -p "$here/build"
asi=$(mktemp "$here/build/.UI.asi.XXXXXX")
cp "$here/target/i686-pc-windows-msvc/release/ui.dll" "$asi"
chmod 644 "$asi"
mv "$asi" "$here/build/UI.asi"
echo "built $here/build/UI.asi"
