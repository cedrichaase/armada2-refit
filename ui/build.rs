// Generates the import libraries from the .def files beside this crate (llvm-dlltool
// --kill-at: the .defs carry decorated names, the real DLLs export undecorated ones;
// menus/build.sh).
use std::{env, path::PathBuf, process::Command};

fn main() {
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let here = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let tool = env::var("LLVM_DLLTOOL").unwrap_or_else(|_| "llvm-dlltool".into());
    for lib in ["kernel32", "user32", "gdi32"] {
        let def = here.join(format!("{lib}.def"));
        println!("cargo:rerun-if-changed={}", def.display());
        let st = Command::new(&tool)
            .args(["-m", "i386", "--kill-at", "-d"])
            .arg(&def)
            .arg("-l")
            .arg(out.join(format!("{lib}.lib")))
            .status()
            .expect("llvm-dlltool not found (install llvm)");
        assert!(st.success(), "llvm-dlltool failed on {lib}.def");
        println!("cargo:rustc-link-lib={lib}");
    }
    println!("cargo:rustc-link-search=native={}", out.display());
    // The font atlases (ui/src/text includes font-regular.bin and font-bold.bin).
    fontbake::bake_fonts(&here.join("../platform/vendor"), &out);
    // The HUD's icons (ui/src/icons.rs includes icons.bin; drawn in fontbake/src/icons.rs).
    fontbake::bake_icons(&out);
    println!("cargo:rerun-if-changed={}", here.join("fontbake/src/icons.rs").display());
    version_resource(&here, &out, "UI.asi", "Armada II Refit: HUD and menu plugin");
    content_files(&here, &out);
}

// The content sets (src/content_sets.rs): every `.ini` under ui/content/ as `FILES`,
// (path relative to content/ with `/`, its text by `include_str!`), sorted by path. A
// new set is a new folder: nothing in the code names one.
fn content_files(here: &std::path::Path, out: &std::path::Path) {
    fn walk(dir: &std::path::Path, base: &std::path::Path, out: &mut Vec<(String, PathBuf)>) {
        let mut es: Vec<_> = std::fs::read_dir(dir).expect("ui/content not readable").flatten().collect();
        es.sort_by_key(|e| e.file_name());
        for e in es {
            let p = e.path();
            if p.is_dir() {
                walk(&p, base, out);
            } else if p.extension().is_some_and(|x| x == "ini") {
                let rel = p.strip_prefix(base).unwrap().components().map(|c| c.as_os_str().to_string_lossy().into_owned()).collect::<Vec<_>>().join("/");
                out.push((rel, p.canonicalize().unwrap()));
            }
        }
    }
    let content = here.join("content").canonicalize().expect("ui/content missing");
    println!("cargo:rerun-if-changed={}", content.display());
    let mut files = Vec::new();
    walk(&content, &content, &mut files);
    files.sort();
    let mut s = String::from("// generated by ui/build.rs from ui/content/\npub static FILES: &[(&str, &str)] = &[\n");
    for (rel, p) in &files {
        s.push_str(&format!("    ({:?}, include_str!({:?})),\n", rel, p.display().to_string()));
    }
    s.push_str("];\n");
    std::fs::write(out.join("content_files.rs"), s).unwrap();
}

// The DLL's version resource, compiled by platform/versioninfo/build-res.sh with the
// layer's and the project's versions from their changelogs, and linked like an object
// (platform/versioninfo/README.md). render3d/build.rs has the same.
fn version_resource(here: &std::path::Path, out: &std::path::Path, file: &str, desc: &str) {
    let vi = here.join("../platform/versioninfo");
    let changelogs = [here.join("CHANGELOG.md"), here.join("../CHANGELOG.md")];
    for p in [vi.join("build-res.sh"), vi.join("versioninfo.rc.in"), here.join("../LICENSE")]
        .iter()
        .chain(&changelogs)
    {
        println!("cargo:rerun-if-changed={}", p.display());
    }
    let [layer, project] = changelogs.map(|p| {
        let text = std::fs::read_to_string(&p).expect("changelog not readable");
        text.lines()
            .find_map(|l| {
                let v = l.strip_prefix("## ")?.split(' ').next()?;
                v.starts_with(|c: char| c.is_ascii_digit()).then(|| v.to_owned())
            })
            .expect("changelog has no '## X.Y.Z' heading")
    });
    let res = out.join("version.res");
    let st = Command::new("bash")
        .arg(vi.join("build-res.sh"))
        .arg(&res)
        .args([file, desc, &layer, &project])
        .status()
        .expect("bash not found");
    assert!(st.success(), "build-res.sh failed (llvm-rc is in llvm)");
    println!("cargo:rustc-link-arg={}", res.display());
}
