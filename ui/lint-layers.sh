#!/usr/bin/env bash
# The layer rules of the UI's sources (README.md, "The engine boundary"), modelled on
# render3d/lint-layers.sh. Everything the UI knows of Armada2.exe lives in src/engine/
# and the generated symbol tables (src/syms_*.rs, started by src/syms.rs); the rest of
# the UI (app.rs, hud/, menus/, widgets/, ...) reaches it only through the facade
# `crate::engine::api`:
#
#   1. boundary  no path into the engine other than the facade outside src/engine/:
#                `engine::<x>` where <x> is not `api` (also `engine::{...}`), and no
#                `syms::` / `syms_<part>::` path (module declarations in lib.rs are not
#                paths)
#   2. address   no hex literal that looks like an address in Armada2.exe
#                (0x400000..0x7fffff) outside src/engine/: addresses come from the
#                profile (profiles/gog-1.1/ui.<part>.toml)
#   3. canvas    the HUD's canvas (1600 x 1200) written nowhere but
#                src/engine/canvas.rs, the one constant (`api::CANVAS`)
#
# Comments are words, not code: an address or the canvas named in a sentence is
# allowed (CLAUDE.md, hard rule 9). Generated files (`// generated by`, src/shaders/)
# are not read.
#
#   lint-layers.sh           every hit as file:line, counts per rule; exit 1 on any hit
#   lint-layers.sh --count   the counts only
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exec python3 - "$here" "$@" <<'PY'
import os, re, sys

here = sys.argv[1]
quiet = '--count' in sys.argv[2:]
src = os.path.join(here, 'src')
GENERATED = re.compile(r'(//|/\*) generated by ')
BOUNDARY = re.compile(r'(?<![\w])engine::(?!api\b)(\w+|\{)|(?<![\w])syms(_\w+)?::')
ADDR = re.compile(r'\b0x0*([4-7][0-9a-fA-F]{5})\b')
CANVAS = re.compile(r'(?<![\w.])(1600|1200)(\.0)?(?![\w.])')


def strip_comments(line):
    out, i, q = [], 0, False
    while i < len(line):
        c = line[i]
        if c == '"' and (i == 0 or line[i - 1] != '\\'):
            q = not q
        if not q and line.startswith('//', i):
            break
        out.append(c)
        i += 1
    return ''.join(out)


def is_engine(rel):
    p = rel.split(os.sep)
    return p[0] == 'engine' or (len(p) == 1 and (p[0] == 'syms.rs' or p[0].startswith('syms_')))


names = {'boundary': 'a path into the engine other than engine::api',
         'address': 'an engine address literal outside src/engine',
         'canvas': 'the HUD canvas outside src/engine/canvas.rs'}
hits = {r: [] for r in names}
for d, dirs, files in os.walk(src):
    dirs[:] = sorted(x for x in dirs if not (x == 'shaders' and d == src))
    for f in sorted(files):
        if not f.endswith('.rs'):
            continue
        path = os.path.join(d, f)
        rel = os.path.relpath(path, src)
        text = open(path, encoding='utf-8', errors='replace').read()
        if GENERATED.match(text):
            continue
        engine = is_engine(rel)
        for n, raw in enumerate(text.split('\n'), 1):
            line = strip_comments(raw)
            if not engine:
                if BOUNDARY.search(line):
                    hits['boundary'].append((rel, n, raw.strip()))
                if ADDR.search(line):
                    hits['address'].append((rel, n, raw.strip()))
            if rel != os.path.join('engine', 'canvas.rs') and not rel.startswith('syms') and CANVAS.search(line):
                hits['canvas'].append((rel, n, raw.strip()))

total = 0
for r, hs in hits.items():
    print(f'{r:8} {len(hs):5}  {names[r]}')
    if not quiet:
        for rel, n, s in hs:
            print(f'                ui/src/{rel}:{n}: {s[:100]}')
    total += len(hs)
print(f'ui/lint-layers.sh: {total} hits')
sys.exit(1 if total else 0)
PY
