#!/usr/bin/env bash
# Rule 4 of render3d/lint-layers.sh ("content"), for the UI's sources (ui/src): the
# game's names are the content set's (ui/content/sets/<set>/ui.ini; README.md,
# "Content sets"), never a literal in code. Outside src/content.rs, a string literal
# may not
#
#   file    name a game file: a stem then `.odf`, `.sod`, `.spr`, `.tga`, `.txt`, `.bik`
#           or `.wav` (`"allrace.tga"`, `"Sprites/cursor.spr"`); a bare extension or a
#           formatted name (`".tga"`, `"{}.tga"`) is the engine's file format, not content
#   race    name a race of the stock game (Federation, Klingon, Romulan, Cardassian, Borg,
#           Species 8472), in any case
#
# A literal that is an engine requirement rather than content stays with a marker on its
# line or the line above: `// lint-allow(content): <reason>` (the reason is required).
# The generated files (syms_*.rs, settings_table.rs: `// generated by` or `@generated`)
# are not read.
#
#   lint-content.sh           report every hit as file:line; exit 1 on any
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exec python3 - "$here" "$@" <<'PY'
import os, re, sys

here = sys.argv[1]
src = os.path.join(here, 'src')
GENERATED = re.compile(r'(//|/\*)[^\n]*(generated by|@generated)')
LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
FILE = re.compile(r'(?<![\w.{}-])[A-Za-z][\w-]*\.(odf|sod|spr|tga|txt|bik|wav)\b', re.I)
RACE = re.compile(r'\b(federation|klingon|romulan|cardassian|borg|species ?8472)\b', re.I)
ALLOW = re.compile(r'//\s*lint-allow\(content\):\s*\S')


def code_of(line):
    # The line without its comment (a `//` outside a literal).
    q = False
    for i, c in enumerate(line):
        if c == '"' and (i == 0 or line[i - 1] != '\\'):
            q = not q
        if not q and line.startswith('//', i):
            return line[:i]
    return line


hits = []
for d, dirs, files in os.walk(src):
    dirs.sort()
    for f in sorted(files):
        if not f.endswith('.rs'):
            continue
        path = os.path.join(d, f)
        rel = os.path.relpath(path, here)
        if rel == os.path.join('src', 'content.rs'):
            continue
        text = open(path, encoding='utf-8', errors='replace').read()
        if GENERATED.search(text.split('\n', 1)[0]):
            continue
        lines = text.split('\n')
        for n, raw in enumerate(lines, 1):
            if ALLOW.search(raw) or (n > 1 and ALLOW.search(lines[n - 2])):
                continue
            for m in LITERAL.finditer(code_of(raw)):
                lit = m.group(1)
                why = 'names a game file' if FILE.search(lit) else 'names a race' if RACE.search(lit) else None
                if why:
                    hits.append(f'{rel}:{n}: "{lit}" {why}')
for h in hits:
    print(f'ui/lint-content.sh: {h}')
print(f'ui/lint-content.sh: {len(hits)} content names outside src/content.rs')
sys.exit(1 if hits else 0)
PY
