"""The legacy plugins the bench still needs, built from the last tag that has them.

HUD.asi, GridLayout.asi and Menus.asi (and their layers' folders) were deleted from the
repository in 15.2.0. The bench needs them in two places only: the stock shell of a
reference case (`Stock shell: embed`, which is Menus.asi with Embed=1 and nothing else,
so that the stock menus take clicks) and an "old install" to retire
(`retire-old-install`, the old half of `display-abi-mismatch`). So they are built once,
from the tag, through `git archive` into a scratch directory (never a worktree), and
cached outside any checkout:

    $A2_DATA/bench/legacy/<tag>/{Menus,HUD,GridLayout}.asi + .ini
                               tree/       the tag's hud/ scripts and a2env, to run
                               chain/      the vendored d3d8_real.dll and d3d9.dll

It is our own code, compiled; nothing of the game is in it (hard rule 8).

    python3 testbench/bench/legacy.py ensure
    python3 testbench/bench/legacy.py install <game dir> menus|hud|grid ...
    python3 testbench/bench/legacy.py embed <game dir>      Menus.asi, stock shell
    python3 testbench/bench/legacy.py seed <game dir> [--res WxH]
                                                  an old install, over a stock game dir
"""
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

try:
    from . import config
except ImportError:                      # run as a script
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
    from bench import config

TAG = 'v13.51.3'                         # the last tag that has menus/, hud/ and grid/
LAYERS = {'menus': ('Menus.asi', 'Menus.ini'),
          'hud': ('HUD.asi', 'HUD.ini'),
          'grid': ('GridLayout.asi', 'GridLayout.ini')}
# what a tag's archive needs to build them: the plugins, the C base, the version resource
PATHS = ['menus', 'hud', 'grid', 'csdk', 'platform/versioninfo', 'platform/vendor/d3d8to9-1.16.0',
         'platform/vendor/dxvk-3.1.1', 'LICENSE', 'CHANGELOG.md', 'a2env.sh', 'a2env.py']
EMBED_INI = ('; written by the Armada II test bench: stock shell, embedded only\r\n'
             '[Menus]\r\nMode=1\r\nDesignWidth=800\r\nDesignHeight=600\r\nIntegerScale=1\r\n'
             'Smooth=0\r\nRaiseShellMode=0\r\nEmbed=1\r\nEscapeReturns=0\r\nUnderlay=0\r\n'
             'Log=1\r\nTrace=0\r\nBackdrops=0\r\n')
DXVK_CONF = ('# generated by tools/renderer-config.sh\n'
             '# written by the Armada II test bench: an old install\'s marked dxvk.conf\n'
             'd3d9.samplerAnisotropy = 16\nd3d9.samplerLodBias = -0.5\n')


def cache_dir(tag=TAG):
    return config.DATA / 'bench' / 'legacy' / tag


def ensure(tag=TAG, say=print):
    """The cache directory of `tag`, built if it is not there."""
    d = cache_dir(tag)
    if (d / '.done').exists():
        return d
    say(f'legacy: building HUD, GridLayout and Menus of {tag} into {d} (once)')
    with tempfile.TemporaryDirectory(prefix='a2legacy-') as tmp:
        tmp = Path(tmp)
        arch = subprocess.run(['git', '-C', str(config.REPO), 'archive', tag, *PATHS],
                              capture_output=True)
        if arch.returncode:
            raise RuntimeError(f'git archive {tag}: {arch.stderr.decode(errors="replace").strip()}')
        subprocess.run(['tar', '-x', '-C', str(tmp)], input=arch.stdout, check=True)
        for layer in LAYERS:
            r = subprocess.run(['bash', str(tmp / layer / 'build.sh')], capture_output=True, text=True)
            if r.returncode:
                raise RuntimeError(f'{layer}/build.sh of {tag} failed:\n{r.stdout}{r.stderr}')
        stage = d.with_name(d.name + f'.build-{os.getpid()}')
        shutil.rmtree(stage, ignore_errors=True)
        (stage / 'chain').mkdir(parents=True)
        for layer, (asi, ini) in LAYERS.items():
            shutil.copy2(tmp / layer / 'build' / asi, stage / asi)
            shutil.copy2(tmp / layer / ini, stage / ini)
        shutil.copy2(tmp / 'platform/vendor/d3d8to9-1.16.0/d3d8.dll', stage / 'chain/d3d8_real.dll')
        shutil.copy2(tmp / 'platform/vendor/dxvk-3.1.1/d3d9.dll', stage / 'chain/d3d9.dll')
        # the hud scripts, to apply to a clone (the build products stay out)
        tree = stage / 'tree'
        for p in ('hud', 'a2env.sh', 'a2env.py'):
            src = tmp / p
            if src.is_dir():
                shutil.copytree(src, tree / p, ignore=shutil.ignore_patterns('build', '*.c', '*.def'))
            else:
                tree.mkdir(exist_ok=True)
                shutil.copy2(src, tree / p)
        (stage / '.done').write_text(tag + '\n')
        shutil.rmtree(d, ignore_errors=True)
        d.parent.mkdir(parents=True, exist_ok=True)
        stage.rename(d)
    return d


def install(game, layers, tag=TAG):
    """Put the plugin(s) and their default inis into a game directory."""
    d = ensure(tag)
    game = Path(game)
    for layer in layers:
        for f in LAYERS[layer]:
            shutil.copy2(d / f, game / f)
        (game / LAYERS[layer][0].replace('.asi', '.log')).unlink(missing_ok=True)


def embed(game, tag=TAG):
    """The bench's stock shell: Menus.asi with Embed=1 and nothing else on."""
    d = ensure(tag)
    game = Path(game)
    shutil.copy2(d / 'Menus.asi', game / 'Menus.asi')
    (game / 'Menus.ini').write_text(EMBED_INI)


def seed(game, res='3440x1440', tag=TAG, say=print):
    """An old install over a stock game directory: the three plugins with their inis, the
    hud scripts' file edits (so the `.a2neb-backup` and `.a2font-backup` files exist), the
    d3d8to9 and DXVK chain files, a marked dxvk.conf, the twelve per-part plugins a
    render3d install replaced, the widened loading screen's backups and the old
    MenuScale folder. Returns the names it added."""
    d = ensure(tag)
    game = Path(game)
    install(game, list(LAYERS), tag)
    added = [f for fs in LAYERS.values() for f in fs]
    env = dict(os.environ, A2_GAME=str(game), A2_GAME_DIR=str(game))
    for script, extra in (('ui-widescreen.py', []), ('ui-font-condense.py', []), ('cursor-aspect.py', [])):
        r = subprocess.run(['python3', str(d / 'tree/hud' / script), '--res', res, *extra], env=env,
                           capture_output=True, text=True)
        if r.returncode:
            raise RuntimeError(f'{script} --res {res} failed:\n{r.stdout}{r.stderr}')
        say(f'legacy: {script} --res {res}: ' + (r.stdout.strip().splitlines() or ['done'])[-1])
    shutil.copy2(d / 'chain/d3d8_real.dll', game / 'd3d8_real.dll')
    shutil.copy2(d / 'chain/d3d9.dll', game / 'd3d9.dll')
    (game / 'dxvk.conf').write_text(DXVK_CONF)
    added += ['d3d8_real.dll', 'd3d9.dll', 'dxvk.conf']
    for n in ('MSAA', 'Lighting', 'Sky', 'Nebulae', 'Surfaces', 'Explosions', 'Shields', 'Repair',
              'Venting', 'Specials', 'Fog', 'Planets'):
        (game / f'{n}.asi').write_bytes(b'MZ old plugin ' + n.encode())
        (game / f'{n}.ini').write_text(f'[{n}]\r\nEnable=1\r\n')
        added += [f'{n}.asi', f'{n}.ini']
    (game / 'MenuScale').mkdir(exist_ok=True)
    (game / 'MenuScale/MainBk.bmp').write_bytes(b'BM old plate')
    # the widened loading screen (models 5.0.x): the live files differ from the backups
    for rel in ['SOD/logo.SOD'] + [f'Textures/RGB/LOADING{i}.tga' for i in range(1, 7)]:
        live = game / rel
        if not live.exists():
            live = next(iter(live.parent.glob(live.name.replace('.tga', '.[tT][gG][aA]'))), None) \
                if rel.endswith('.tga') else None
        if live is None or not live.exists():
            continue
        shutil.copy2(live, str(live) + '.a2neb-backup')
        with open(live, 'ab') as f:
            f.write(b'\0' * 16)
        added.append(str(live.relative_to(game)))
    return added


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    cmd, args = argv[1], argv[2:]
    if cmd == 'ensure':
        print(ensure())
    elif cmd == 'install':
        install(args[0], args[1:])
    elif cmd == 'embed':
        embed(args[0])
    elif cmd == 'seed':
        res = args[args.index('--res') + 1] if '--res' in args else '3440x1440'
        print('\n'.join(seed(args[0], res)))
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
