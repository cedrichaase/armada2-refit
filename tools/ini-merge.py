#!/usr/bin/env python3
"""ini-merge.py [--before-comments] <shipped.ini> <installed.ini>: add to the installed
file every key the shipped one has and it lacks, in its own section; the player's values
stay. Every installer that ships an .ini uses it (render3d, ui, display, qol, online, the
Bink proxy), so a reinstall never overwrites a hand-edited file.

--before-comments puts an added key before the blank lines *and comment lines* that end
its section (they belong to the next section), as render3d/install.sh's own merge did for
Render3D.ini; without it only blank lines are skipped.

Retired defaults (RETIRED below), keyed by the installed file's name: a key whose meaning
changed has its old default replaced by the shipped value, wherever it still holds it.
Unlike `Defaults=` this needs no number in the file, so it serves files that never had one
(Render3D.ini).

One exception, when the shipped defaults themselves change: a `Defaults=` key numbers
them, in whichever section of the shipped file has it (`[UI]` in UI.ini, `[Display8]`
in Display8.ini), and a file brought up to an older number (or none: 1) has each key
that a newer set changed moved to the new default, but only where it still holds the
old default. A value the player changed stays. UI.ini's Defaults 2 switched every part
of the UI on (the HUD's panels, the menus, the loading screen, the cursor), which were
all 0 before (ui/README.md, "Installing"); Display8.ini's Defaults 2 made the stub on
Backend=auto the default (display/README.md, "Installing"); its Defaults 3 drops Mode, Real
and `d3d9` from Backend and carries a marked dxvk.conf's sampler keys into [Samplers]."""
import re
import sys

# The section that holds `Defaults=` -> {defaults number -> {(section, key): the value
# the previous defaults had}}.
UPGRADES = {
    'ui': {
        2: {('ui', 'cursor'): '0',
            **{('hud', k): '0' for k in ('bar', 'info', 'minimap', 'selection', 'unitview',
                                         'resources', 'buttons', 'messages', 'pause', 'replay',
                                         'overlay', 'chat', 'comm', 'dropplayer', 'loadwait')},
            ('menus', 'enable'): '0',
            ('loading', 'enable'): '0'},
    },
    'display8': {
        3: {},   # code: display8_defaults3
        2: {('display8', 'mode'): 'forward',
            ('display8', 'backend'): 'd3d9'},
    },
}

# Display8.ini's Defaults 3 (Direct3D 9 and forward mode removed from Display8): not a map of
# old defaults, so it is code, mirrored in publish/installer/install.sh and install.ps1.
# Mode and Real go; `d3d9` goes from Backend= (nothing left: the shipped value); the three
# sampler keys dxvk.conf gave Direct3D 9 are carried into [Samplers], from a dxvk.conf
# bearing renderer/renderer-config.sh's marker, where the player set none.
DXVK_MARKER = '# generated by tools/renderer-config.sh'
DXVK_SAMPLERS = (('d3d9.sampleranisotropy', 'anisotropy'),
                 ('d3d9.samplerlodbias', 'lodbias'),
                 ('d3d9.clampnegativelodbias', 'clampnegativelodbias'))


def dxvk_samplers(path):
    """{[Samplers] key (lower case): value} of the game's marked dxvk.conf, else {}."""
    try:
        text = open(path, encoding='latin-1').read()
    except OSError:
        return {}
    if not any(l.strip() == DXVK_MARKER for l in text.splitlines()):
        return {}
    conf = {}
    for l in text.splitlines():
        m = re.match(r'^\s*([\w.]+)\s*=\s*(\S+)', l)
        if m and not l.lstrip().startswith('#'):
            conf[m.group(1).lower()] = m.group(2)
    out = {}
    for ck, key in DXVK_SAMPLERS:
        if ck in conf:
            v = conf[ck]
            if key == 'clampnegativelodbias':
                v = {'true': '1', 'false': '0'}.get(v.lower(), v)
            out[key] = v
    return out


def same_number(a, b):
    try:
        return float(a) == float(b)
    except ValueError:
        return a.lower() == b.lower()


def display8_defaults3(lines, have_vals, ship_vals, label, dxvk_path):
    """Edits `lines` in place."""
    drop = set()
    for key in ('mode', 'real'):
        if ('display8', key) in have_vals:
            i, v = have_vals[('display8', key)]
            drop.add(i)
            print(f'  {label}: [display8] {KEY.match(lines[i]).group(1)}={v} dropped (defaults 3)')
    if ('display8', 'backend') in have_vals:
        i, v = have_vals[('display8', 'backend')]
        toks = [t.strip() for t in v.split(',') if t.strip()]
        kept = [t for t in toks if t.lower() != 'd3d9']
        if len(kept) != len(toks):
            new = ','.join(kept) if kept else ship_vals.get(('display8', 'backend'), (0, 'auto'))[1]
            lines[i] = f'{KEY.match(lines[i]).group(1)}={new}'
            print(f'  {label}: [display8] Backend {v} -> {new} (defaults 3)')
    names = {'anisotropy': 'Anisotropy', 'lodbias': 'LodBias',
             'clampnegativelodbias': 'ClampNegativeLodBias'}
    added = []
    for key, v in dxvk_samplers(dxvk_path).items():
        ship = ship_vals.get(('samplers', key), (0, 'auto'))[1]
        if same_number(v, ship):
            continue
        if ('samplers', key) in have_vals:
            i, cur = have_vals[('samplers', key)]
            if cur.lower() != 'auto':
                continue
            lines[i] = f'{KEY.match(lines[i]).group(1)}={v}'
        else:
            added.append(f'{names[key]}={v}')
        print(f'  {label}: [samplers] {names[key]} -> {v} (from dxvk.conf, defaults 3)')
    for i in sorted(drop, reverse=True):
        del lines[i]
    if added:
        at = next((j for j, l in enumerate(lines)
                   if SEC.match(l) and SEC.match(l).group(1).lower() == 'samplers'), None)
        if at is None:
            lines += ['', '[Samplers]']
            at = len(lines) - 1
        lines[at + 1:at + 1] = added


# installed file name (lower case) -> {(section, key): the old default}.
RETIRED = {
    'render3d.ini': {
        ('lights', 'beamlight'): '1.0',        # render3d 0.26.0: a line of even emission
        ('lights', 'beamreach'): '40',
        ('nebulae', 'litexplosion'): '0.75',   # render3d 0.27.0: a core and a wash in the gas
    },
}

KEY = re.compile(r'^\s*(\w+)\s*=\s*(.*?)\s*$')
SEC = re.compile(r'^\s*\[([^\]]+)\]')


def parse(text):
    secs, cur = {}, None
    for line in text.splitlines():
        m = SEC.match(line)
        if m:
            cur = m.group(1).lower()
            secs.setdefault(cur, [])
        elif cur is not None:
            secs[cur].append(line)
    return secs


def values(lines):
    """{(section, key): (line index, value)} of a file's lines."""
    out, cur = {}, None
    for i, l in enumerate(lines):
        m = SEC.match(l)
        if m:
            cur = m.group(1).lower()
            continue
        m = KEY.match(l)
        if cur is not None and m and not l.lstrip().startswith(';'):
            out[(cur, m.group(1).lower())] = (i, m.group(2))
    return out


args = sys.argv[1:]
before_comments = '--before-comments' in args
args = [a for a in args if a != '--before-comments']
# latin-1 maps every byte to one character, so a player's cp1252 comment survives the rewrite.
shipped_text = open(args[0], encoding='latin-1').read()
new = parse(shipped_text)
lines = open(args[1], encoding='latin-1').read().splitlines()

# The defaults' upgrade, before any key is added.
ship_vals = values(shipped_text.splitlines())
have_vals = values(lines)
dsec = next((s for (s, k) in ship_vals if k == 'defaults'), None)
label = args[1].replace('\\', '/').rsplit('/', 1)[-1]
def defaults_n(vals, what):
    """The leading integer of Defaults= (`2 ; note` is 2); anything else counts as 0."""
    v = vals.get((dsec, 'defaults'), (0, '1'))[1] or '1'
    m = re.match(r'\s*(\d+)', v)
    if not m:
        print(f'  {label}: Defaults={v!r} is not a number, taken as 0 ({what})')
    return int(m.group(1)) if m else 0


ship_n = defaults_n(ship_vals, 'shipped')
have_n = defaults_n(have_vals, 'installed')
upgrades = UPGRADES.get(dsec, {})
for n in sorted(upgrades):
    if not have_n < n <= ship_n:
        continue
    if dsec == 'display8' and n == 3:
        import os
        display8_defaults3(lines, have_vals, ship_vals, label,
                           os.path.join(os.path.dirname(os.path.abspath(args[1])), 'dxvk.conf'))
        have_vals = values(lines)
        continue
    for (sec, key), old in upgrades[n].items():
        if (sec, key) in have_vals and (sec, key) in ship_vals:
            i, v = have_vals[(sec, key)]
            if v == old and v != ship_vals[(sec, key)][1]:
                name = KEY.match(lines[i]).group(1)
                lines[i] = f'{name}={ship_vals[(sec, key)][1]}'
                print(f'  {label}: [{sec}] {name} {v} -> {ship_vals[(sec, key)][1]} (defaults {n})')
if (dsec, 'defaults') in have_vals and have_n < ship_n:
    i, _ = have_vals[(dsec, 'defaults')]
    lines[i] = f'{KEY.match(lines[i]).group(1)}={ship_n}'

# Retired defaults: the shipped line replaces the old default's, as it is spelled there.
retired = RETIRED.get(label.lower(), {})
if retired:
    shipped_lines = {}
    for sec, body in new.items():
        for l in body:
            m = re.match(r'^(\w+)=(.*)$', l)
            if m:
                shipped_lines[(sec, m.group(1).lower())] = l
    cur = None
    for i, l in enumerate(lines):
        m = SEC.match(l)
        if m:
            cur = m.group(1).lower()
            continue
        m = KEY.match(l)
        if m and cur is not None:
            k = (cur, m.group(1).lower())
            if k in retired and m.group(2) == retired[k] and k in shipped_lines:
                lines[i] = shipped_lines[k]

have = parse('\n'.join(lines))
for sec, body in new.items():
    keys = {k.lower() for k in (re.match(r'^(\w+)=', l).group(1) for l in have.get(sec, []) if re.match(r'^(\w+)=', l))}
    missing = [l for l in body if re.match(r'^(\w+)=', l) and l.split('=')[0].lower() not in keys]
    if not missing:
        continue
    if sec in have:
        # after the last line of that section
        at, cur = len(lines), None
        for i, l in enumerate(lines):
            m = SEC.match(l)
            if m:
                if cur == sec:
                    at = i
                    break
                cur = m.group(1).lower()
        while at > 0 and (not lines[at - 1].strip() or
                          (before_comments and lines[at - 1].lstrip().startswith(';'))):
            at -= 1
        lines[at:at] = missing
    else:
        name = next(l for l in shipped_text.splitlines() if l.strip().lower() == '[' + sec + ']')
        lines += ['', name] + missing
open(args[1], 'w', encoding='latin-1').write('\n'.join(lines) + '\n')
