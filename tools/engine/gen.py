#!/usr/bin/env python3
"""The symbol profiles' generator (phase 8 contract P5; crates/a2engine/README.md).

    gen.py                         write every profile file's `out`
    gen.py --check                 exit 1, naming them, when a generated file is out of date
    gen.py --emit FILE [--lang rs|c]   print the module generated from one profile file
    gen.py --list-hooks PLUGIN     print a plugin's hook ids, one per line
    --profiles DIR ...             read these profile sets instead of the repository's

Every build of the file's game is in the output, flattened, as static arrays: the
run-time code has no inheritance logic. Stdlib only.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import profiles  # noqa: E402
from profiles import NONE, ProfileError, hexbytes  # noqa: E402

ROOT = profiles.ROOT
KIND_CODE = {k: i for i, k in enumerate(
    ['fn', 'call', 'jmp', 'slot', 'label', 'patch', 'scan', 'vtable', 'global', 'rtti', 'field', 'value'])}
KIND_RS = {k: k.capitalize() for k in KIND_CODE}
KIND_RS['fn'] = 'Fn'


def upper(s):
    return s.replace('.', '_').replace('-', '_').upper()


def esc(s):
    return str(s).replace('\\', '\\\\').replace('"', '\\"')


def header(t, c=False):
    rel = os.path.relpath(t.file.path, ROOT)
    more = [os.path.relpath(b['build'].files[t.fname].path, ROOT)
            for b in t.builds[1:] if t.fname in b['build'].files]
    src = ', '.join([rel] + more)
    line = f'generated by tools/engine/gen.py from {src}; do not edit'
    return f'/* {line} */' if c else f'// {line}'


def consts(t):
    """{id: value} for fields and values, refusing builds that disagree (FO-3)."""
    out = {}
    for k, sid in enumerate(t.sym_ids):
        kind = t.kind(k)
        if kind not in profiles.CONST_KINDS:
            continue
        key = 'offset' if kind == 'field' else 'value'
        vals = {b['entries'][k][key] for b in t.builds if b['entries'][k] is not None}
        if len(vals) > 1:
            raise ProfileError(f'{t.file.rel()}: {sid} differs between builds: run-time fields and values are FO-3\'s')
        out[sid] = vals.pop()
    return out


def n_resolved(t, b):
    n = 0
    for e in b['entries']:
        if e is None:
            continue
        ub = [f'{t.plugin}.{u}' for u in (e.get('used_by') or [])]
        if ub and all(u in b['blocked'] for u in ub):
            continue
        n += 1
    return n


def note_for_block(sym, why):
    if why.startswith('is changed by '):
        by = why[len('is changed by '):].split(' ')[0]
        return f'Stands down: {sym} is changed by {by}, not yet verified'[:120]
    return f'Stands down: {why[3:]}'[:120]


def entry_fields(t, e):
    """(present, addr, end, target, vtable, index, chain, check, mask, section, count, value)."""
    if e is None:
        return None
    kind = e['kind']
    idx = {s: i for i, s in enumerate(t.sym_ids)}
    addr = e.get('addr', 0) if kind in profiles.ADDR_KINDS or kind == 'scan' else 0
    target = NONE
    if kind in ('call', 'jmp', 'slot') and e.get('target') not in (None, 'any'):
        target = idx[e['target']]
    vtable = idx[e['vtable']] if kind == 'slot' else NONE
    check, mask = b'', b''
    if kind == 'scan':
        check, mask = hexbytes(e['pattern'], e['id'], pattern=True)
    elif e.get('check'):
        check, _ = hexbytes(e['check'], e['id'])
    value = e.get('offset', 0) if kind == 'field' else e.get('value', 0) if kind == 'value' else 0
    return dict(addr=addr, end=e.get('end', 0), target=target, vtable=vtable,
                index=e.get('index', 0), chain=bool(e.get('chain', False)), check=check, mask=mask,
                section=e.get('section', ''), count=e.get('count', 0), value=value)


# ---- Rust -------------------------------------------------------------------------

def rs_bytes(b):
    return '&[' + ', '.join(f'0x{x:02x}' for x in b) + ']'


def emit_rs(t):
    o = [header(t), '//! The symbol table of `' + t.plugin + '` (crates/a2engine/README.md).', '']
    cs = consts(t)
    o.append('pub mod sym {')
    for k, sid in enumerate(t.sym_ids):
        if t.kind(k) not in profiles.CONST_KINDS:
            o.append(f'    pub const {upper(sid)}: a2engine::Sym = a2engine::Sym({k});')
    o += ['}', '', 'pub mod hook {']
    for h, name in enumerate(t.hooks):
        o.append(f'    pub const {upper(name)}: a2engine::HookId = a2engine::HookId({h});')
    o += ['}', '', 'pub mod field {']
    for k, sid in enumerate(t.sym_ids):
        if t.kind(k) == 'field':
            o.append(f'    pub const {upper(sid)}: usize = {cs[sid]:#x};')
    o += ['}', '', 'pub mod value {']
    for k, sid in enumerate(t.sym_ids):
        if t.kind(k) == 'value':
            o.append(f'    pub const {upper(sid)}: i32 = {cs[sid]};')
    o += ['}', '']
    o.append('pub const SYMS: &[a2engine::SymDef] = &[')
    for k, sid in enumerate(t.sym_ids):
        d = t.defs[sid]
        o.append(f'    a2engine::SymDef {{ id: "{esc(sid)}", symbol: "{esc(d.get("symbol", ""))}", kind: a2engine::Kind::{KIND_RS[d["kind"]]} }},')
    o += ['];', '', 'pub const HOOKS: &[a2engine::HookDef] = &[']
    for h, name in enumerate(t.hooks):
        hd = t.file.hooks[name]
        rows = ', '.join(f'"{esc(r)}"' for r in (hd.get('rows') or []))
        syms = ', '.join(str(k) for k in t.hook_syms(name))
        run = 'true' if hd.get('unknown') == 'run' else 'false'
        o.append(f'    a2engine::HookDef {{ id: "{esc(t.hook_ids[h])}", run_unknown: {run}, rows: &[{rows}], syms: &[{syms}] }},')
    o += ['];', '', 'pub const BUILDS: &[a2engine::Build] = &[']
    for b in t.builds:
        bb = b['build']
        p = bb.pe
        o.append('    a2engine::Build {')
        o.append(f'        name: "{esc(bb.name)}",')
        o.append(f'        key: "{esc(bb.key)}",')
        o.append(f'        timestamp: {p.get("timestamp", 0):#x},')
        o.append(f'        image_size: {p.get("image_size", 0):#x},')
        o.append(f'        sections: {p.get("sections", 0):#010x},')
        o.append(f'        image_base: {p.get("image_base", 0):#x},')
        o.append(f'        n_resolved: {n_resolved(t, b)},')
        o.append(f'        content: "{esc(bb.content_for(t.fname))}",')
        o.append('        entries: &[')
        for k, e in enumerate(b['entries']):
            f = entry_fields(t, e)
            if f is None:
                o.append('            a2engine::Entry::ABSENT,')
                continue
            o.append(
                f'            a2engine::Entry {{ present: true, addr: {f["addr"]:#x}, end: {f["end"]:#x}, '
                f'target: {f["target"]:#x}, vtable: {f["vtable"]:#x}, index: {f["index"]}, chain: {"true" if f["chain"] else "false"}, '
                f'check: {rs_bytes(f["check"])}, mask: {rs_bytes(f["mask"])}, section: "{esc(f["section"])}", '
                f'count: {f["count"]}, value: {f["value"]} }}, // {t.sym_ids[k]}')
        o.append('        ],')
        o.append('        blocked: &[')
        for hid, (sym, why) in b['blocked'].items():
            h = t.hook_ids.index(hid)
            o.append(f'            a2engine::Block {{ hook: {h}, symbol: "{esc(sym)}", why: "{esc(why)}", note: "{esc(note_for_block(sym, why))}" }},')
        o.append('        ],')
        o.append('    },')
    nh, ns = len(t.hooks), len(t.sym_ids)
    n_scan = sum(1 for k in range(ns) if t.kind(k) == 'scan')
    o += ['];', '',
          f'static HOOK_STATE: [core::sync::atomic::AtomicU64; {nh}] = [const {{ core::sync::atomic::AtomicU64::new(0) }}; {nh}];',
          f'static SYM_FLAGS: [core::sync::atomic::AtomicU8; {ns}] = [const {{ core::sync::atomic::AtomicU8::new(0) }}; {ns}];',
          f'static SYM_ADDR: [core::sync::atomic::AtomicUsize; {ns}] = [const {{ core::sync::atomic::AtomicUsize::new(0) }}; {ns}];',
          f'static NOTES: [a2engine::Note; {nh}] = [const {{ a2engine::Note::new() }}; {nh}];',
          'static RT: a2engine::Runtime = a2engine::Runtime::new(&HOOK_STATE, &SYM_FLAGS, &SYM_ADDR, &NOTES);',
          '',
          'pub static TABLE: a2engine::Table = a2engine::Table {',
          f'    game: "{esc(t.gs.game)}",',
          f'    plugin: "{esc(t.plugin)}",',
          '    syms: SYMS,',
          '    hooks: HOOKS,',
          '    builds: BUILDS,',
          f'    n_scan: {n_scan},',
          '    rt: &RT,',
          '};']
    return '\n'.join(o) + '\n'


# ---- C ----------------------------------------------------------------------------

def c_bytes(name, b):
    if not b:
        return None
    return f'static const A2E_U8 {name}[] = {{' + ', '.join(f'0x{x:02x}' for x in b) + '};'


def emit_c(t):
    p, P = t.plugin, upper(t.plugin)
    guard = f'{P}_ENGINE_SYMS_H'
    cs = consts(t)
    o = [header(t, c=True),
         f'/* The symbol table of {p} (crates/a2engine/README.md); included once, after a2engine.h. */',
         f'#ifndef {guard}', f'#define {guard}', '']
    for k, sid in enumerate(t.sym_ids):
        kind = t.kind(k)
        if kind == 'field':
            o.append(f'#define {P}_F_{upper(sid)} 0x{cs[sid]:x}')
        elif kind == 'value':
            o.append(f'#define {P}_V_{upper(sid)} {cs[sid]}')
        else:
            o.append(f'#define {P}_S_{upper(sid)} {k}')
    for h, name in enumerate(t.hooks):
        o.append(f'#define {P}_H_{upper(name)} {h}')
    o.append('')
    for k, sid in enumerate(t.sym_ids):
        if t.kind(k) not in profiles.CONST_KINDS:
            o.append(f'A2E_U32 a2s_{p}_{sid} __attribute__((used));')
    o.append('')
    o.append(f'static A2E_U32 *const {p}_vars[] = {{')
    for k, sid in enumerate(t.sym_ids):
        o.append(f'    0,' if t.kind(k) in profiles.CONST_KINDS else f'    &a2s_{p}_{sid},')
    o += ['};', '', f'static const A2ESymDef {p}_syms[] = {{']
    for k, sid in enumerate(t.sym_ids):
        d = t.defs[sid]
        o.append(f'    {{"{esc(sid)}", "{esc(d.get("symbol", ""))}", {KIND_CODE[d["kind"]]}}},')
    o.append('};')
    for h, name in enumerate(t.hooks):
        hd = t.file.hooks[name]
        rows = hd.get('rows') or []
        syms = t.hook_syms(name)
        o.append(f'static const char *const {p}_h{h}_rows[] = {{' + ''.join(f'"{esc(r)}", ' for r in rows) + '0};')
        o.append(f'static const A2E_U16 {p}_h{h}_syms[] = {{' + ', '.join(str(k) for k in syms) + (', ' if syms else '') + '0};')
    o.append(f'static const A2EHookDef {p}_hooks[] = {{')
    for h, name in enumerate(t.hooks):
        hd = t.file.hooks[name]
        run = 1 if hd.get('unknown') == 'run' else 0
        o.append(f'    {{"{esc(t.hook_ids[h])}", {run}, {p}_h{h}_rows, {len(hd.get("rows") or [])}, {p}_h{h}_syms, {len(t.hook_syms(name))}}},')
    o.append('};')
    for bi, b in enumerate(t.builds):
        ents = []
        for k, e in enumerate(b['entries']):
            f = entry_fields(t, e)
            if f is None:
                ents.append('    {0},')
                continue
            cn = mn = '0'
            cb = c_bytes(f'{p}_b{bi}_c{k}', f['check'])
            if cb:
                o.append(cb)
                cn = f'{p}_b{bi}_c{k}'
            mb = c_bytes(f'{p}_b{bi}_m{k}', f['mask'])
            if mb:
                o.append(mb)
                mn = f'{p}_b{bi}_m{k}'
            ents.append(
                f'    {{1, {int(f["chain"])}, 0x{f["target"]:x}, 0x{f["vtable"]:x}, {f["index"]}, {f["count"]}, {len(f["check"])}, '
                f'0x{f["addr"]:x}, 0x{f["end"]:x}, {f["value"]}, {cn}, {mn}, "{esc(f["section"])}"}}, /* {t.sym_ids[k]} */')
        o.append(f'static const A2EEntry {p}_b{bi}_entries[] = {{')
        o += ents
        o.append('};')
        o.append(f'static const A2EBlock {p}_b{bi}_blocked[] = {{')
        for hid, (sym, why) in b['blocked'].items():
            o.append(f'    {{{t.hook_ids.index(hid)}, "{esc(sym)}", "{esc(why)}", "{esc(note_for_block(sym, why))}"}},')
        o.append('    {0xffff, 0, 0, 0}')
        o.append('};')
    o.append(f'static const A2EBuild {p}_builds[] = {{')
    for bi, b in enumerate(t.builds):
        bb = b['build']
        pe_ = bb.pe
        o.append(f'    {{"{esc(bb.name)}", "{esc(bb.key)}", 0x{pe_.get("timestamp", 0):x}, 0x{pe_.get("image_size", 0):x}, '
                 f'0x{pe_.get("sections", 0):08x}, 0x{pe_.get("image_base", 0):x}, {p}_b{bi}_entries, {p}_b{bi}_blocked, '
                 f'{len(b["blocked"])}, {n_resolved(t, b)}}},')
    nh, ns = len(t.hooks), len(t.sym_ids)
    n_scan = sum(1 for k in range(ns) if t.kind(k) == 'scan')
    o += ['};', '',
          f'static A2E_U8 {p}_hook_state[{max(nh, 1)}];',
          f'static A2E_U8 {p}_sym_flags[{max(ns, 1)}];',
          f'static A2E_U32 {p}_sym_addr[{max(ns, 1)}];',
          f'static char {p}_notes[{max(nh, 1)}][A2E_NOTE_MAX + 1];', '',
          f'static const A2ETable {P}_ENGINE = {{',
          f'    "{esc(t.gs.game)}", "{esc(p)}",',
          f'    {p}_syms, {ns}, {p}_hooks, {nh}, {p}_builds, {len(t.builds)}, {n_scan},',
          f'    {p}_vars, {p}_hook_state, {p}_sym_flags, {p}_sym_addr, {p}_notes',
          '};', '', f'#endif /* {guard} */']
    return '\n'.join(o) + '\n'


def emit(t, lang=None):
    lang = lang or t.file.lang
    if lang == 'rust' or lang == 'rs':
        return emit_rs(t)
    if lang == 'c':
        return emit_c(t)
    raise ProfileError(f'{t.file.rel()}: lang must be c or rust')


def wanted(games=None):
    out = []
    for t in profiles.tables(games):
        if not t.file.out:
            raise ProfileError(f'{t.file.rel()}: no out')
        out.append((os.path.join(ROOT, t.file.out), emit(t)))
    return out


def main(argv):
    roots = None
    if '--profiles' in argv:
        i = argv.index('--profiles')
        roots = []
        j = i + 1
        while j < len(argv) and not argv[j].startswith('--'):
            roots.append(os.path.abspath(argv[j]))
            j += 1
        argv = argv[:i] + argv[j:]
    try:
        games = profiles.load_game_sets(roots)
        if argv[:1] == ['--emit']:
            path = os.path.abspath(argv[1])
            lang = argv[3] if argv[2:3] == ['--lang'] else None
            for t in profiles.tables(games):
                if os.path.abspath(t.file.path) == path:
                    sys.stdout.write(emit(t, lang))
                    return 0
            print(f'gen.py: {argv[1]} is not the root file of a profile table', file=sys.stderr)
            return 2
        if argv[:1] == ['--list-hooks']:
            for t in profiles.tables(games):
                if t.plugin == argv[1]:
                    for h in t.hook_ids:
                        print(h)
            return 0
        files = wanted(games)
    except ProfileError as e:
        print(f'gen.py: {e}', file=sys.stderr)
        return 1
    if argv == ['--check']:
        stale = []
        for path, text in files:
            try:
                cur = open(path).read()
            except OSError:
                cur = None
            if cur != text:
                stale.append(os.path.relpath(path, ROOT))
        for s in stale:
            print(f'out of date: {s} (run tools/engine/gen.py)')
        return 1 if stale else 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    for path, text in files:
        try:
            cur = open(path).read()
        except OSError:
            cur = None
        if cur != text:
            with open(path, 'w') as f:
                f.write(text)
            print(f'wrote {os.path.relpath(path, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
