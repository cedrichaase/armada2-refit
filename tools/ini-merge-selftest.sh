#!/usr/bin/env bash
# Offline check of tools/ini-merge.py: on Render3D.ini fixtures its output must be byte-identical
# to the merge render3d/install.sh used to carry inline (kept as selftest/render3d-inline-merge.py).
# Needs nothing from the game. Usage: tools/ini-merge-selftest.sh
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ship="$here/../render3d/Render3D.ini"
t=$(mktemp -d); trap 'rm -rf "$t"' EXIT
n=0; bad=0
check() {  # name, installed fixture file
    mkdir -p "$t/old" "$t/new"
    cp "$2" "$t/old/Render3D.ini"; cp "$2" "$t/new/Render3D.ini"
    python3 "$here/selftest/render3d-inline-merge.py" "$ship" "$t/old/Render3D.ini"
    python3 "$here/ini-merge.py" --before-comments "$ship" "$t/new/Render3D.ini" >/dev/null
    n=$((n+1))
    if cmp -s "$t/old/Render3D.ini" "$t/new/Render3D.ini"; then echo "ok   $1"
    else echo "FAIL $1"; diff "$t/old/Render3D.ini" "$t/new/Render3D.ini" | head || true; bad=$((bad+1)); fi
}
cp "$ship" "$t/f1"; check "identical to shipped" "$t/f1"
for k in 2 3 7; do
    awk -v k=$k '/^[A-Za-z0-9_]+=/ { c++; if (c % k == 0) next } { print }' "$ship" > "$t/f2$k"
    check "every ${k}th key missing" "$t/f2$k"
done
sed -e 's/^BeamLight=.*/BeamLight=1.0/' -e 's/^BeamReach=.*/BeamReach=40/' \
    -e 's/^LitExplosion=.*/LitExplosion=0.75/' -e 's/^Samples=.*/Samples=2/' "$ship" > "$t/f3"
check "retired defaults and a hand edit" "$t/f3"
awk '/^\[/ { sec=$0 } sec=="[Nebulae]" { next } { print }' "$ship" | sed 's/^BeamLight=.*/BeamLight=1.0/' > "$t/f4"
check "a section missing" "$t/f4"
printf '[Lights]\nBeamLight=1.0\n\n; a note the player wrote\n[Other]\nX=1\n' > "$t/f5"
check "short hand-written file" "$t/f5"
# Display8.ini's Defaults 3: Mode and Real dropped, d3d9 out of Backend, a marked dxvk.conf's
# sampler keys carried into [Samplers] unless the player set them. Fixture, not the shipped file.
cat > "$t/d8ship.ini" <<'EOF'
[Display8]
Defaults=3
Backend=auto
VSync=1

[Samplers]
Anisotropy=auto
LodBias=auto
ClampNegativeLodBias=auto
EOF
d8() {  # name, installed text, dxvk.conf text (or empty for none), then the grep -x lines wanted, ! prefix = absent
    local name="$1" ini="$2" conf="$3"; shift 3
    rm -rf "$t/d8"; mkdir -p "$t/d8"; printf '%s\n' "$ini" > "$t/d8/Display8.ini"
    [ -z "$conf" ] || printf '%s\n' "$conf" > "$t/d8/dxvk.conf"
    python3 "$here/ini-merge.py" "$t/d8ship.ini" "$t/d8/Display8.ini" >/dev/null
    n=$((n+1)); local ok=1 w
    for w in "$@"; do
        if [ "${w:0:1}" = '!' ]; then ! grep -qix "${w:1}" "$t/d8/Display8.ini" || ok=0
        else grep -qx "$w" "$t/d8/Display8.ini" || ok=0; fi
    done
    if [ $ok = 1 ]; then echo "ok   $name"; else echo "FAIL $name"; cat "$t/d8/Display8.ini"; bad=$((bad+1)); fi
}
MARK='# generated by tools/renderer-config.sh'
CONF="$MARK
d3d9.samplerAnisotropy = 16
d3d9.samplerLodBias = -0.5
d3d9.clampNegativeLodBias = False"
d8 "defaults 3: d3d12,d3d9 -> d3d12" $'[Display8]\nBackend=d3d12,d3d9' "" "Backend=d3d12" "Defaults=3"
d8 "defaults 3: d3d9 -> shipped" $'[Display8]\nBackend=d3d9' "" "Backend=auto"
d8 "defaults 3: Mode and Real dropped" $'[Display8]\nMode=forward\nReal=auto\nVSync=0' "" "!Mode=.*" "!Real=.*" "VSync=0"
d8 "defaults 3: marked dxvk.conf carried" $'[Display8]\nVSync=0\n\n[Samplers]\nAnisotropy=auto' "$CONF" \
    "Anisotropy=16" "LodBias=-0.5" "ClampNegativeLodBias=0"
d8 "defaults 3: no [Samplers] yet, carried" $'[Display8]\nVSync=0' "$CONF" "LodBias=-0.5" "ClampNegativeLodBias=0"
d8 "defaults 3: True maps to 1" $'[Display8]\nVSync=0' "$MARK
d3d9.clampNegativeLodBias = True" "ClampNegativeLodBias=1"
d8 "defaults 3: a player's dxvk.conf not carried" $'[Display8]\nVSync=0' "${CONF#*$'\n'}" "LodBias=auto" "Anisotropy=auto"
d8 "defaults 3: the player's own key kept" $'[Display8]\nVSync=0\n\n[Samplers]\nLodBias=-1' "$CONF" "LodBias=-1" "Anisotropy=16"
d8 "defaults 3: already at 3, left alone" $'[Display8]\nDefaults=3\nMode=stub' "$CONF" "Mode=stub" "LodBias=auto"
# UI.ini: a per-game default that moved (Roots' [Menus] Generic mirror -> widgets) reaches an
# install that still holds the old default; a value the player set stays; with the shipped
# value equal to the old one (Armada II) nothing changes.
ui() {  # name, shipped Generic, installed Generic, wanted Generic
    printf '[Menus]\nEnable=1\nGeneric=%s\nForms=0\n' "$2" > "$t/uiship.ini"
    printf '[Menus]\nEnable=1\nGeneric=%s\n' "$3" > "$t/ui.ini"
    python3 "$here/ini-merge.py" "$t/uiship.ini" "$t/ui.ini" >/dev/null
    n=$((n+1))
    if grep -qx "Generic=$4" "$t/ui.ini" && grep -qx 'Forms=0' "$t/ui.ini"; then echo "ok   $1"
    else echo "FAIL $1"; cat "$t/ui.ini"; bad=$((bad+1)); fi
}
ui "ui: Roots default moved, old default updated" widgets mirror widgets
ui "ui: the player's own value kept" widgets off off
ui "ui: Armada II, mirror stays" mirror mirror mirror
# UI.ini on Roots: [HUD] Messages moved 0 -> 1 in ui/defaults/fo-roots.ini (decision 324). With
# A2_PROFILE=fo-roots an install still at 0 follows; on Armada II (shipped 1 already) a 0 is the
# player's and stays.
msg() {  # name, profile, installed Messages, wanted Messages
    printf '[HUD]\nEnable=1\nMessages=1\nPause=1\n' > "$t/uiship.ini"
    printf '[HUD]\nEnable=1\nMessages=%s\n' "$3" > "$t/ui.ini"
    A2_PROFILE="$2" python3 "$here/ini-merge.py" "$t/uiship.ini" "$t/ui.ini" >/dev/null
    n=$((n+1))
    if grep -qx "Messages=$4" "$t/ui.ini" && grep -qx 'Pause=1' "$t/ui.ini"; then echo "ok   $1"
    else echo "FAIL $1"; cat "$t/ui.ini"; bad=$((bad+1)); fi
}
msg "ui: Roots Messages 0 -> 1" fo-roots 0 1
msg "ui: Roots Messages already 1" fo-roots 1 1
msg "ui: Armada II, a 0 stays" armada2 0 0
echo "$n cases, $bad failed"; [ "$bad" = 0 ]
