#!/usr/bin/env bash
# Host test of retire.sh on a mock game directory (no game, no assets, no bench):
#
#   retire/selftest.sh
#
# A game directory with every kind of entry in known.txt, plus things that must stay: a
# player's own dxvk.conf, a d3d9.dll that is not ours, the menu plates the UI draws, a
# Sky/ recipe of the player's. --check changes nothing; a run restores and removes; a
# second run does nothing; --chain takes the chain's files out by hash and marker only.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
game="$work/game"
export XDG_DATA_HOME="$work/share" XDG_CACHE_HOME="$work/cache" HOME="$work/home"
mkdir -p "$game"/{misc,Sprites,SOD,Sky,Menus,MenuScale,Textures/RGB} "$XDG_DATA_HOME/a2-vkbasalt" "$HOME"
fail=0
ok() { echo "ok   $*"; }
bad() { echo "FAIL $*"; fail=1; }
is() { [ -e "$game/$1" ] && ok "$1 stays/exists" || bad "$1 missing"; }
gone() { [ ! -e "$game/$1" ] && ok "$1 gone" || bad "$1 still there"; }
content() { [ "$(cat "$game/$1")" = "$2" ] && ok "$1 = $2" || bad "$1 is $(cat "$game/$1"), want $2"; }

# Legacy plugins, the twelve, their recipes.
for n in HUD GridLayout Menus MenuScale MSAA Lighting Sky Nebulae Surfaces Explosions Shields Repair Venting Specials Fog Planets; do
    : > "$game/$n.asi"; : > "$game/$n.ini"; : > "$game/$n.log"
done
: > "$game/MenuScale/a.bmp"; : > "$game/Sky/Mine.ini"
# A Sky recipe as an earlier release shipped it goes; one the player edited (same name) stays.
cp "$here/../render3d/content/sky/mbgred.ini" "$game/Sky/mbgred.ini"
{ cat "$here/../render3d/content/sky/mbgaqu.ini"; echo "; my tweak"; } > "$game/Sky/mbgaqu.ini"
: > "$game/Menus/MainBk.bmp"; : > "$game/A2EngineTest.ini"
# The logs older builds wrote beside the exe (the plugins' own .asi stay).
for n in Display8 Render3D UI QOL QOLRules Online BinkProxy; do : > "$game/$n.log"; done
: > "$game/Render3D.asi"
# The hud scripts' edits and their backups.
echo stock-cfg > "$game/misc/gui_fed.cfg.a2neb-backup"; echo wide-cfg > "$game/misc/gui_fed.cfg"
echo stock-same > "$game/misc/gui_kli.cfg.a2neb-backup"; echo stock-same > "$game/misc/gui_kli.cfg"
printf 'Arrow Curs_Arrow 0 0 32 32\n' > "$game/Sprites/cursor.spr"
echo stock-cur > "$game/Textures/RGB/Curs_Arrow.tga.a2neb-backup"; echo sq-cur > "$game/Textures/RGB/Curs_Arrow.tga"
echo other > "$game/Textures/RGB/Mnebula4.tga.a2neb-backup"; echo up > "$game/Textures/RGB/Mnebula4.tga"
echo stock-font > "$game/Textures/RGB/FontFinal4_12.tga.a2font-backup"; echo cond > "$game/Textures/RGB/FontFinal4_12.tga"
echo stock-spr > "$game/Sprites/FontFinal4_12.spr.a2font-backup"; echo cond-spr > "$game/Sprites/FontFinal4_12.spr"
echo stock-sod > "$game/SOD/logo.SOD.a2neb-backup"; echo wide-sod > "$game/SOD/logo.SOD"
echo stock-l1 > "$game/Textures/RGB/LOADING1.tga.a2neb-backup"; echo wide-l1 > "$game/Textures/RGB/LOADING1.tga"
# The chain, and a player's own.
echo "# generated by tools/renderer-config.sh" > "$game/dxvk.conf"
echo not-ours > "$game/d3d9.dll"; echo not-ours > "$game/d3d8_real.dll"

echo "-- --check"
before=$(cd "$game" && find . -type f | sort | xargs sha256sum | sha256sum)
"$here/retire.sh" --check "$game" | sed 's/^/   /'
after=$(cd "$game" && find . -type f | sort | xargs sha256sum | sha256sum)
[ "$before" = "$after" ] && ok "--check touched nothing" || bad "--check changed the directory"
is HUD.asi

echo "-- run"
"$here/retire.sh" "$game" | sed 's/^/   /'
for n in HUD GridLayout Menus MenuScale MSAA Lighting Sky Nebulae Surfaces Explosions Shields Repair Venting Specials Fog Planets; do
    gone "$n.asi"; gone "$n.ini"; gone "$n.log"
done
gone MenuScale; gone Sky/mbgred.ini; is Sky/mbgaqu.ini; is Sky/Mine.ini; is Menus/MainBk.bmp; gone A2EngineTest.ini
for n in Display8 Render3D UI QOL QOLRules Online BinkProxy; do gone "$n.log"; done
is Render3D.asi
content misc/gui_fed.cfg stock-cfg; gone misc/gui_fed.cfg.a2neb-backup
content misc/gui_kli.cfg stock-same; gone misc/gui_kli.cfg.a2neb-backup
content Textures/RGB/Curs_Arrow.tga stock-cur; gone Textures/RGB/Curs_Arrow.tga.a2neb-backup
content Textures/RGB/Mnebula4.tga up; is Textures/RGB/Mnebula4.tga.a2neb-backup
content Textures/RGB/FontFinal4_12.tga stock-font; gone Textures/RGB/FontFinal4_12.tga.a2font-backup
content Sprites/FontFinal4_12.spr stock-spr; gone Sprites/FontFinal4_12.spr.a2font-backup
content SOD/logo.SOD stock-sod; gone SOD/logo.SOD.a2neb-backup
content Textures/RGB/LOADING1.tga stock-l1; gone Textures/RGB/LOADING1.tga.a2neb-backup
is dxvk.conf; is d3d9.dll; is d3d8_real.dll
[ ! -e "$XDG_DATA_HOME/a2-vkbasalt" ] && ok "vkBasalt bloom gone" || bad "vkBasalt bloom stays"

echo "-- a second run"
second=$("$here/retire.sh" "$game")
[ "$second" = "retire: no file-based fixes to put back" ] && ok "nothing left to do" || bad "second run: $second"

echo "-- --chain"
printf 'dxvk' > "$game/d3d9.dll"   # not the vendored hash
"$here/retire.sh" --chain "$game" | sed 's/^/   /'
gone dxvk.conf; is d3d9.dll; is d3d8_real.dll
echo "# a player's own" > "$game/dxvk.conf"
"$here/retire.sh" --chain "$game" >/dev/null
is dxvk.conf

echo "-- --chain carries a marked dxvk.conf's samplers into Display8.ini"
printf '# generated by tools/renderer-config.sh\nd3d9.samplerLodBias = -1.25\n' > "$game/dxvk.conf"
printf '[Display8]\nDefaults=2\nBackend=d3d12,d3d9\nMode=forward\n' > "$game/Display8.ini"
"$here/retire.sh" --chain "$game" | sed 's/^/   /'
gone dxvk.conf
grep -q '^LodBias=-1.25' "$game/Display8.ini" && ok "LodBias carried into [Samplers]" || bad "LodBias not carried"
grep -qi '^Mode=' "$game/Display8.ini" && bad "Mode= stays" || ok "Mode= dropped"
printf '# generated by tools/renderer-config.sh\nd3d9.samplerLodBias = -0.5\n' > "$game/dxvk.conf"; rm -f "$game/Display8.ini"
"$here/retire.sh" --chain "$game" >/dev/null
gone dxvk.conf; is Display8.ini   # a full file from the stub: display/install merges into it

echo "-- a dxvk.conf stays when its samplers cannot be carried"
printf '# generated by tools/renderer-config.sh\nd3d9.samplerLodBias = -1.25\n' > "$game/dxvk.conf"; rm -f "$game/Display8.ini"
mkdir -p "$work/badbin"
printf '#!/bin/sh\ncase "$1" in *ini-merge.py) exit 1 ;; esac\nexec /usr/bin/env -i PATH="$ORIGPATH" python3 "$@"\n' > "$work/badbin/python3"; chmod +x "$work/badbin/python3"
out=$(ORIGPATH="$PATH" PATH="$work/badbin:$PATH" "$here/retire.sh" --chain "$game" 2>&1) || true
case "$out" in *"dxvk.conf stays"*) ok "said so" ;; *) bad "no word on the kept dxvk.conf: $out" ;; esac
is dxvk.conf; gone Display8.ini
"$here/retire.sh" --chain "$game" >/dev/null
gone dxvk.conf

[ "$fail" = 0 ] && echo "retire selftest: all ok" || { echo "retire selftest: FAILED"; exit 1; }
